func catalogueRoot(t *testing.T, text string) string {
	t.Helper()
	root := t.TempDir()
	if text != "" {
		p := filepath.Join(root, catalogueSeed)
		if err := os.MkdirAll(filepath.Dir(p), 0o750); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(text), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	return root
}

func TestCatalogueCheck(t *testing.T) {
	if _, ok := registry[catalogueID]; !ok || catalogueID != "SVC-G01" {
		t.Fatalf("check %s is not registered", catalogueID)
	}
	for name, c := range map[string]struct {
		scenario string
		seed     string
		want     string // "" = PASS, else a part of the reason of the FAIL
	}{
		"the objects are the seed's and say class and lifecycle": {"catalogue-ok", catalogueSeedText, ""},
		"a name of the seed has no object":                       {"catalogue-missing", catalogueSeedText, "region region-a lacks 1 seeded objects: bp-b"},
		"an object the seed does not name":                       {"catalogue-extra", catalogueSeedText, "holds 1 seeded objects the seed does not name: bp-ghost"},
		"both at once":                                           {"catalogue-both", catalogueSeedText, "lacks 1 seeded objects (bp-b) and holds 1 the seed does not name (bp-ghost)"},
		"an object without a class":                              {"catalogue-no-class", catalogueSeedText, "1 of 2 seeded Blueprint objects of region region-a carry no spec.class or no spec.lifecycle: bp-b"},
		"an object without a lifecycle":                          {"catalogue-no-lifecycle", catalogueSeedText, "carry no spec.class or no spec.lifecycle: bp-a"},
		"the resource is not served":                             {"catalogue-not-served", catalogueSeedText, "doesn't have a resource type"},
		"the seed cannot be read":                                {"catalogue-ok", "", "the seed of the candidate cannot be read"},
		"the seed names no object":                               {"catalogue-ok", "{{- if .Values.catalogSeed.enabled }}\n{{- end }}\n", "names no Blueprint object: nothing was measured"},
		"only the primary region is judged":                      {"catalogue-follower-empty", catalogueSeedText, ""},
	} {
		r := runCheck(t, c.scenario, catalogueCheck{}, &CheckContext{RepoRoot: catalogueRoot(t, c.seed)})
		got := r.run.Checks[0]
		switch {
		case c.want == "" && got.Status != Pass:
			t.Errorf("%s: want PASS, got %+v", name, got)
		case c.want != "" && (got.Status != Fail || !strings.Contains(got.Reason, c.want)):
			t.Errorf("%s: want FAIL with %q, got %+v", name, c.want, got)
		}
	}
	// Three steps, and the evidence holds what was compared.
	r := runCheck(t, "catalogue-extra", catalogueCheck{}, &CheckContext{RepoRoot: catalogueRoot(t, catalogueSeedText)})
	if len(r.run.Steps) != 3 {
		t.Fatalf("want three steps, got %d", len(r.run.Steps))
	}
	s1, s2 := r.run.Steps[0], r.run.Steps[1]
	if s1.ID != "SVC-G01.1" || s1.Status != Pass || s1.Evidence["seeded"] != 2 {
		t.Errorf("step 1 does not hold the evidence: %+v", s1)
	}
	if s2.ID != "SVC-G01.2" || s2.Status != Fail || s2.Evidence["seeded"] != 3 ||
		strings.Join(s2.Evidence["extra"].([]string), ",") != "bp-ghost" {
		t.Errorf("step 2 does not hold the evidence: %+v", s2)
	}
	// The names of the seed: the first name after each kind line, in order, once.
	names, err := catalogueNames(catalogueRoot(t, catalogueSeedText))
	if err != nil || strings.Join(names, ",") != "bp-a,bp-b" {
		t.Errorf("catalogueNames = %v, %v; want bp-a,bp-b", names, err)
	}
}
