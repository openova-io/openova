// catalogueSeedText is a seed as scripts/generate-catalog.py writes it: two
// objects, Helm template lines around them.
const catalogueSeedText = `{{- /* Generated by python3 scripts/generate-catalog.py from every blueprint.yaml. */ -}}
{{- if .Values.catalogSeed.enabled }}
---
apiVersion: catalyst.openova.io/v1
kind: Blueprint
metadata:
  name: bp-a
  labels:
    catalyst.openova.io/managed-by: catalog-seed
spec:
  version: 1.0.0
  endpoints:
  - name: ui
---
apiVersion: catalyst.openova.io/v1
kind: Blueprint
metadata:
  name: bp-b
spec:
  version: 1.0.0
{{- end }}
`

// catalogueBlueprint is a fixture Blueprint object. seeded adds the label of
// the seed; class and lifecycle are set when not empty.
func catalogueBlueprint(name string, seeded bool, class, lifecycle string) obj {
	meta := kubeMeta("", name)
	if seeded {
		meta["labels"] = obj{catalogueLabel: catalogueLabelValue}
	}
	spec := obj{"version": "1.0.0"}
	if class != "" {
		spec["class"] = class
	}
	if lifecycle != "" {
		spec["lifecycle"] = lifecycle
	}
	return obj{"metadata": meta, "spec": spec}
}

