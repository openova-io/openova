#!/usr/bin/env python3
"""generator_registry.py - the files a registered generator writes, and the sources it writes them from.

  python3 scripts/generator_registry.py [--repo DIR]    one line per file: <file><TAB><generator><TAB><sources>

Ruling 147 (18 November 2026): a file that a registered generator writes is judged at its source, not as a copy.
The registry is the job named "regenerate and prove no diff" of a workflow under .github/workflows/: the check
that runs the generators and is red when a committed output differs from what they write. Everything below is
read from that job at run time; there is no list of paths here.

  generator  a script that a step of the job runs (python3, node, bash or sh <path>), relative to the step's
             working-directory.
  file       a file whose first 15 lines say "generated by <generator>" for a generator of the job, and whose
             path the job or one of its generators names (relative to the repository, to the step's
             working-directory, or to the generator's folder). A file that names a generator the job does not
             run, or that the job and its generators do not name, is not listed.
  sources    the files that the path filters of the workflow (on.pull_request.paths and on.push.paths) watch,
             without the generators, the files the job names and the workflow itself: what the generator reads.
             A workflow without a path filter declares no sources.

scripts/check-provider-leaks.py and scripts/check-upstream-literals.sh do not count the lines of a listed file
when it has sources and each lies inside their own scan; its lines are then counted where they are written. A
hand-edited copy cannot hide behind this: the registry job is red when a committed output differs from what
its generator writes.

Exit codes: 0 the list is printed (it may be empty); 2 a workflow of the job is not YAML, or PyYAML is missing.
"""
import argparse
import os
import re
import subprocess
import sys

JOB = "regenerate and prove no diff"
HEAD = 15
WORKFLOW = re.compile(r"^\.github/workflows/[^/]+\.ya?ml$")
RUNS = re.compile(r"(?:^|[\s;&|(])(?:python3?|node|bash|sh)\s+(?:-\S+\s+)*([\w./-]+\.(?:py|mjs|cjs|js|sh))(?![\w.-])")
PATH = re.compile(r"(?<![\w./-])((?:\.\.?/)*[\w.-]+(?:/[\w.-]+)+)")
CLAIM = re.compile(r"generated by\s+(?:(?:python3?|node|bash|sh)\s+)?([\w./-]+)", re.IGNORECASE)


class RegistryError(Exception):
    """A workflow of the registry job cannot be read."""


def read_text(repo, path):
    full = os.path.join(repo, path)
    if os.path.isfile(full) and not os.path.islink(full):
        return open(full, "rb").read().decode("utf-8", "replace")


def tracked(repo):
    """The files of the repository: `git ls-files` in a checkout, else every file below repo."""
    if os.path.exists(os.path.join(repo, ".git")):
        out = subprocess.run(["git", "-C", repo, "ls-files", "-z"], check=True, stdout=subprocess.PIPE).stdout
        return [p for p in out.decode("utf-8", "surrogateescape").split("\0") if p]
    found = []
    for top, dirs, files in os.walk(repo):
        dirs[:] = [d for d in dirs if d not in (".git", "node_modules")]
        found += [os.path.relpath(os.path.join(top, f), repo).replace(os.sep, "/") for f in files]
    return sorted(found)


def filter_re(pattern):
    """A path filter of GitHub Actions: ** matches any characters, * and ? match no slash."""
    out, i = "", 0
    while i < len(pattern):
        if pattern.startswith("**/", i):
            out, i = out + "(?:.*/)?", i + 3
        elif pattern.startswith("**", i):
            out, i = out + ".*", i + 2
        elif pattern[i] in "*?":
            out, i = out + ("[^/]*" if pattern[i] == "*" else "[^/]"), i + 1
        else:
            out, i = out + re.escape(pattern[i]), i + 1
    return re.compile(out + r"\Z")


def working_directory(node):
    defaults = node.get("defaults") if isinstance(node, dict) else None
    run = defaults.get("run") if isinstance(defaults, dict) else None
    wd = run.get("working-directory") if isinstance(run, dict) else None
    return wd if isinstance(wd, str) else ""


def named(text, bases):
    """The paths text names, each resolved from every base folder."""
    return {os.path.normpath(os.path.join(b, t)).replace(os.sep, "/") for t in PATH.findall(text) for b in bases}


def registry_jobs(repo, paths, reader):
    """(workflow, document, job) for every job named JOB."""
    for wf in sorted(p for p in paths if WORKFLOW.match(p)):
        text = reader(repo, wf)
        if not text or JOB not in text:
            continue
        try:
            import yaml
        except ImportError:
            raise RegistryError("PyYAML is needed to read " + wf)
        try:
            doc = yaml.safe_load(text)
        except yaml.YAMLError as e:
            raise RegistryError(f"{wf}: not YAML: {e}")
        jobs = doc.get("jobs") if isinstance(doc, dict) else None
        for job in (jobs.values() if isinstance(jobs, dict) else ()):
            if isinstance(job, dict) and job.get("name") == JOB:
                yield wf, doc, job


def generated_files(repo, paths, reader=read_text):
    """{file: (generator, [source, ...])} for every file a generator of the registry job writes."""
    have, files = set(paths), {}
    for wf, doc, job in registry_jobs(repo, paths, reader):
        base = working_directory(job) or working_directory(doc)
        generators, names = [], set()
        for step in job.get("steps") or ():
            if not isinstance(step, dict) or not isinstance(step.get("run"), str):
                continue
            wd = step.get("working-directory") if isinstance(step.get("working-directory"), str) else base
            for token in RUNS.findall(step["run"]):
                script = os.path.normpath(os.path.join(wd, token)).replace(os.sep, "/")
                if script in have and script not in generators:
                    generators.append(script)
            names |= named(step["run"], ("", wd))
        for script in generators:
            names |= named(reader(repo, script) or "", ("", os.path.dirname(script)))
        names = (names & have) - set(generators) - {wf}
        on = doc.get("on", doc.get(True))
        filters = []
        for event in ("pull_request", "push"):
            spec = on.get(event) if isinstance(on, dict) else None
            if isinstance(spec, dict) and isinstance(spec.get("paths"), list):
                filters += [p for p in spec["paths"] if isinstance(p, str)]
        take = [filter_re(p) for p in filters if not p.startswith("!")]
        drop = [filter_re(p[1:]) for p in filters if p.startswith("!")]
        sources = sorted(p for p in paths if any(r.match(p) for r in take) and not any(r.match(p) for r in drop)
                         and p not in names and p not in generators and p != wf)
        for path in sorted(names):
            head = "\n".join((reader(repo, path) or "").split("\n")[:HEAD])
            claims = {c.rstrip(".,;:") for c in CLAIM.findall(head)}
            generator = next((g for g in generators if g in claims), None)
            if generator and path not in files:
                files[path] = (generator, sources)
    return files


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--repo", default=os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    a = ap.parse_args()
    try:
        files = generated_files(a.repo, tracked(a.repo))
    except (RegistryError, subprocess.CalledProcessError) as e:
        print(f"generator-registry: {e}", file=sys.stderr)
        return 2
    for path, (generator, sources) in sorted(files.items()):
        print(f"{path}\t{generator}\t{' '.join(sources)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
