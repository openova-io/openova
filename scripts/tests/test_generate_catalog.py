#!/usr/bin/env python3
"""Unit tests of scripts/generate-catalog.py (SVC-150, SVC-160, SVC-170). Run: python3 scripts/tests/test_generate_catalog.py

Each test builds a small repository tree in a scratch directory and runs the generator's main() on it with --root.
The seed tests render the generated seed with helm template (HELM_BIN, default helm), as a Sovereign's install does.
"""
import contextlib
import importlib.util
import io
import json
import os
import shutil
import subprocess
import sys
import tempfile
import unittest

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location("generate_catalog", os.path.join(HERE, "..", "generate-catalog.py"))
gc = importlib.util.module_from_spec(spec)
spec.loader.exec_module(gc)

BP = """kind: Blueprint
metadata:
  name: bp-{name}
  labels:
    example.org/team: t
spec:
  version: 1.2.3
  visibility: listed
  class: application
  lifecycle: experimental
  card:
    title: {title}
    summary: |
      First line: with a colon.
      Second line # not a comment.
    tags: [one, two]
  depends:{depends}
  endpoints:
    - name: ui
"""


def blueprint(name, title="T", depends="\n  - blueprint: bp-a"):
    return BP.format(name=name, title=title, depends=depends or " []")


class Tree(unittest.TestCase):
    def setUp(self):
        self.root = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, self.root)
        self.put("platform/a/blueprint.yaml", blueprint("a", depends=""))
        self.put("products/b/blueprint.yaml", blueprint("b"))
        self.put("platform/a/chart/Chart.yaml", "name: bp-a\nversion: 1.2.3\n")
        self.put("products/b/chart/Chart.yaml", "name: bp-b\nversion: 1.2.3\n")
        self.put(gc.KIT + "/01-a.yaml", "kind: HelmRelease\n")
        self.put(gc.KIT + "/02-bp-b.yaml", "kind: HelmRelease\n")
        self.put(gc.KIT + "/kustomization.yaml", "resources: []\n")

    def put(self, rel, text):
        p = os.path.join(self.root, rel)
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, "w") as f:
            f.write(text)

    def read(self, rel, base=None):
        with open(os.path.join(base or self.root, rel)) as f:
            return f.read()

    def run_main(self, *args, env=None):
        err = io.StringIO()
        with contextlib.redirect_stdout(io.StringIO()), contextlib.redirect_stderr(err):
            code = gc.main(["--root", self.root] + list(args), {"SOURCE_DATE_EPOCH": "0"} if env is None else env)
        return code, err.getvalue()

    def test_writes_both_outputs_in_place(self):
        self.assertEqual(self.run_main()[0], 0)
        cat = json.loads(self.read(gc.OUT_JSON))
        self.assertEqual([b["id"] for b in cat["blueprints"]], ["bp-a", "bp-b"])
        self.assertEqual([k["id"] for k in cat["bootstrapKit"]], ["bp-a", "bp-b"])
        self.assertEqual(cat["generatedAt"], "1970-01-01T00:00:00.000Z")
        self.assertIn('"id": "bp-b"', self.read(gc.OUT_TS))
        self.assertIn("Generated by python3 scripts/generate-catalog.py", self.read(gc.OUT_TS))

    def test_block_scalar_summary_and_flow_tags_round_trip(self):
        self.run_main()
        b = json.loads(self.read(gc.OUT_JSON))["blueprints"][1]
        self.assertEqual(b["summary"], "First line: with a colon.\nSecond line # not a comment.\n")
        self.assertEqual(b["tags"], ["one", "two"])
        self.assertEqual((b["title"], b["class"], b["lifecycle"], b["depends"], b["hasUserUIEndpoint"]),
                         ("T", "application", "experimental", ["bp-a"], True))
        self.assertNotIn("category", b)
        self.assertNotIn("section", b)
        self.assertNotIn('"summary": "|"', self.read(gc.OUT_TS))

    def test_deterministic(self):
        self.run_main()
        first = (self.read(gc.OUT_JSON), self.read(gc.OUT_TS))
        self.assertEqual(self.run_main(env={})[0], 0)          # no SOURCE_DATE_EPOCH: the unchanged content keeps its stamp
        self.assertEqual((self.read(gc.OUT_JSON), self.read(gc.OUT_TS)), first)

    def test_changed_content_gets_a_new_stamp(self):
        self.run_main()
        self.put("platform/a/blueprint.yaml", blueprint("a", title="New", depends=""))
        self.run_main(env={"SOURCE_DATE_EPOCH": "86400"})
        self.assertEqual(json.loads(self.read(gc.OUT_JSON))["generatedAt"], "1970-01-02T00:00:00.000Z")

    def test_check(self):
        self.assertEqual(self.run_main("--check")[0], 1)       # nothing generated yet
        self.run_main()
        self.assertEqual(self.run_main("--check")[0], 0)
        self.put(gc.OUT_TS, self.read(gc.OUT_TS) + "// hand edit\n")
        code, err = self.run_main("--check")
        self.assertEqual(code, 1)
        self.assertIn(gc.OUT_TS + " is stale", err)

    def test_dry_run_leaves_the_tree_alone(self):
        out = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, out)
        self.assertEqual(self.run_main("--dry-run", out)[0], 0)
        self.assertFalse(os.path.exists(os.path.join(self.root, gc.OUT_JSON)))
        self.assertEqual(len(json.loads(self.read(gc.OUT_JSON, out))["blueprints"]), 2)

    def assert_input_error(self, rel, text, words):
        self.put(rel, text)
        code, err = self.run_main()
        self.assertEqual(code, 2)
        self.assertIn(rel + ": " + words, err)
        self.assertFalse(os.path.exists(os.path.join(self.root, gc.OUT_JSON)))

    def test_not_yaml(self):
        self.assert_input_error("platform/c/blueprint.yaml", "kind: [\n", "not YAML")

    def test_not_a_blueprint(self):
        self.assert_input_error("platform/c/blueprint.yaml", "kind: Chart\nmetadata:\n  name: bp-c\n", "not a Blueprint")

    def test_bad_name(self):
        self.assert_input_error("platform/c/blueprint.yaml", blueprint("other").replace("bp-other", "other"), "metadata.name")

    def test_two_blueprints_with_one_name(self):
        self.assert_input_error("products/a/blueprint.yaml", blueprint("a"), "Blueprint bp-a is also declared")

    def test_missing_dependency(self):
        self.assert_input_error("platform/c/blueprint.yaml", blueprint("c", depends="\n  - bp-none"), "depends names bp-none")

    def test_missing_input_folder(self):
        for d in ("platform", "products", gc.KIT):
            with self.subTest(folder=d):
                self.setUp()
                shutil.rmtree(os.path.join(self.root, d))
                code, err = self.run_main()
                self.assertEqual(code, 2)
                self.assertIn(d + "/: input folder is missing", err)
                self.assertFalse(os.path.exists(os.path.join(self.root, gc.OUT_JSON)))

    def seed(self):
        """The generated seed as helm template renders it in the chart that holds it: {name: object}."""
        self.put(gc.SEED_CHART + "/Chart.yaml", "apiVersion: v2\nname: bp-catalyst-platform\nversion: 9.8.7\n")
        self.put(gc.SEED_CHART + "/values.yaml", "catalogSeed:\n  enabled: true\n")
        self.assertEqual(self.run_main()[0], 0)
        r = subprocess.run([os.environ.get("HELM_BIN", "helm"), "template", "x", ".", "--show-only", "templates/catalog-seed/blueprints.yaml"],
                           cwd=os.path.join(self.root, gc.SEED_CHART), stdout=subprocess.PIPE, stderr=subprocess.PIPE, universal_newlines=True)
        self.assertEqual(r.returncode, 0, r.stderr)
        return {d["metadata"]["name"]: d for d in yaml.safe_load_all(r.stdout) if d}

    def test_seed_holds_one_object_per_file_with_a_derived_source(self):
        self.put("platform/a/blueprint.yaml", blueprint("a", depends="") + "  manifests:\n    chart: bp-a\n  upgrades: [x]\n  owner: team\n")
        seed = self.seed()
        self.assertEqual(sorted(seed), ["bp-a", "bp-b"])
        a = seed["bp-a"]
        self.assertEqual((a["apiVersion"], a["kind"]), ("catalyst.openova.io/v1", "Blueprint"))
        self.assertEqual(a["spec"]["source"], {"kind": "HelmRepository", "type": "oci", "url": "oci://ghcr.io/openova-io",
                                               "chart": "bp-a", "version": "1.2.3"})
        self.assertEqual(list(a["spec"]).index("source"), list(a["spec"]).index("manifests") + 1)
        self.assertNotIn("upgrades", a["spec"])
        self.assertNotIn("owner", a["spec"])
        self.assertEqual(a["spec"]["card"]["summary"], "First line: with a colon.\nSecond line # not a comment.\n")
        self.assertEqual(a["metadata"]["labels"], {"catalyst.openova.io/managed-by": "catalog-seed", "catalyst.openova.io/origin": "openova-public",
                                                   "catalyst.openova.io/curation": "openova-public", "example.org/team": "t",
                                                   "app.kubernetes.io/managed-by": "Helm", "app.kubernetes.io/instance": "x"})
        self.assertIn("Generated by python3 scripts/generate-catalog.py", self.read(gc.OUT_SEED).split("\n", 1)[0])

    def test_seed_keeps_a_runtime_template_literal(self):
        self.put("platform/a/blueprint.yaml", blueprint("a", depends="").replace("    - name: ui\n",
                 "    - name: ui\n      hostnameTemplate: \"{{.AppName}}.{{.OrgDomain}}\"\n") + "  sso:\n    realm: '{{.OrgSlug}}'\n")
        a = self.seed()["bp-a"]
        self.assertEqual(a["spec"]["endpoints"][0]["hostnameTemplate"], "{{.AppName}}.{{.OrgDomain}}")
        self.assertEqual(a["spec"]["sso"]["realm"], "{{.OrgSlug}}")

    def test_seed_version_of_the_chart_that_holds_the_seed(self):
        self.put("platform/catalyst-platform/blueprint.yaml", blueprint("catalyst-platform", depends="").replace("1.2.3", "0.0.0"))
        self.put(gc.CHART_LOCATIONS, "charts:\n  bp-catalyst-platform: products/catalyst/chart\n")
        cp = self.seed()["bp-catalyst-platform"]["spec"]
        self.assertEqual(self.read(gc.OUT_SEED).count("version: {{ .Chart.Version | quote }}"), 2)
        self.assertEqual((cp["version"], cp["source"]["version"]), ("9.8.7", "9.8.7"))

    def test_seed_version_of_a_registered_pin(self):
        self.put("platform/u/blueprint.yaml", blueprint("u", depends="").replace("1.2.3", "0.0.0"))
        self.put(gc.UNPUBLISHED, "unpublished:\n  - chart: bp-u\n    version: \"1.0.0\"\n")
        u = self.seed()["bp-u"]["spec"]
        self.assertEqual((u["version"], u["source"]["version"]), ("1.0.0", "1.0.0"))

    def test_seed_exclusions_and_class(self):
        self.put("platform/a/blueprint.yaml", blueprint("a", depends="").replace("class: application", "class: data-service"))
        self.put("products/b/blueprint.yaml", blueprint("b", depends=""))
        self.put("platform/c/blueprint.yaml", blueprint("c", depends="").replace("visibility: listed", "visibility: unlisted")
                 .replace("class: application", "class: platform-component"))
        self.put("platform/c/chart/Chart.yaml", "name: bp-c\nversion: 1.2.3\n")
        self.put(gc.CATALOG + "/" + gc.EXCLUSIONS, "exclusions:\n  - blueprint: bp-c\n    reason: not in the catalogue\n")
        seed = self.seed()
        self.assertEqual(sorted(seed), ["bp-a", "bp-b"])
        self.assertEqual([(seed[n]["spec"]["class"], seed[n]["spec"]["lifecycle"]) for n in ("bp-a", "bp-b")],
                         [("data-service", "experimental"), ("application", "experimental")])
        got = {b["id"]: (b["class"], b["lifecycle"]) for b in json.loads(self.read(gc.OUT_JSON))["blueprints"]}
        self.assertEqual(got, {"bp-a": ("data-service", "experimental"), "bp-b": ("application", "experimental"),
                               "bp-c": ("platform-component", "experimental")})
        self.assertIn('"class": "platform-component"', self.read(gc.OUT_TS))

    def test_seed_check_finds_a_hand_edit(self):
        self.assertEqual(self.run_main()[0], 0)
        self.put(gc.OUT_SEED, self.read(gc.OUT_SEED).replace("version: 1.2.3", "version: 1.2.4", 1))
        code, err = self.run_main("--check")
        self.assertEqual(code, 1)
        self.assertIn(gc.OUT_SEED + " is stale", err)

    def test_self_test_passes(self):
        with contextlib.redirect_stdout(io.StringIO()):
            self.assertEqual(gc.self_test(), 0)


if __name__ == "__main__":
    sys.exit(0 if unittest.main(exit=False).result.wasSuccessful() else 1)
