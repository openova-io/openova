#!/usr/bin/env python3
"""provider-registry.py - the provider registry all.go, generated from the adapter folders.

It reads   products/catalyst/bootstrap/api/go.mod                 (the module path)
           products/catalyst/bootstrap/api/internal/providers/*/  (the adapter folders)
It writes  products/catalyst/bootstrap/api/internal/providers/all/all.go

`go generate ./internal/providers/all` runs it (the directive is in all/gen.go).

Usage, from any directory:
  python3 scripts/generators/provider-registry.py              write the file
  python3 scripts/generators/provider-registry.py --check      write nothing; exit 1 when the file on disk differs
  python3 scripts/generators/provider-registry.py --self-test  prove every rule on a throw-away tree

Exit codes: 0 done or current; 1 the file is stale, or a self-test case failed;
2 an input is missing or cannot be read, or breaks a rule below.

The rules:
  - an adapter is a folder beside all/ that holds a file provider.go;
  - its name matches ^[a-z][a-z0-9-]{1,30}$ (the pack name);
  - all.go imports each adapter once, for its init() only, sorted by name;
  - there is at least one adapter.

This file names no cloud: the provider-leak scanner reads it as shared code.
"""
import difflib
import os
import re
import sys
import tempfile

SCRIPT = "scripts/generators/provider-registry.py"
API = "products/catalyst/bootstrap/api"
PROVIDERS = API + "/internal/providers"
OUTPUT = PROVIDERS + "/all/all.go"
NAME = re.compile(r"^[a-z][a-z0-9-]{1,30}$")


class InputError(Exception):
    """An input is missing, cannot be read, or breaks a rule of this generator."""


def module_path(root):
    try:
        with open(os.path.join(root, API, "go.mod"), encoding="utf-8") as handle:
            for line in handle:
                if line.startswith("module "):
                    return line.split()[1]
    except OSError as error:
        raise InputError("%s/go.mod: cannot be read: %s" % (API, error.strerror))
    raise InputError("%s/go.mod: has no module line" % API)


def adapters(root):
    folder = os.path.join(root, PROVIDERS)
    try:
        names = sorted(os.listdir(folder))
    except OSError as error:
        raise InputError("%s: cannot be listed: %s" % (PROVIDERS, error.strerror))
    found = [n for n in names if n != "all" and os.path.isfile(os.path.join(folder, n, "provider.go"))]
    for name in found:
        if not NAME.match(name):
            raise InputError("%s/%s: the folder name does not match %s" % (PROVIDERS, name, NAME.pattern))
    if not found:
        raise InputError("%s: no folder holds a provider.go" % PROVIDERS)
    return found


def generate(root):
    module = module_path(root)
    lines = [
        "// Code generated by %s. DO NOT EDIT." % SCRIPT,
        "",
        "// Package all imports every provider adapter, so that each adapter's",
        "// init() registers it with providers.RegisterProvider. A binary that",
        "// needs the adapters imports this package once.",
        "//",
        "// An adapter is a folder beside this one that holds provider.go. To",
        "// change the list, add or remove such a folder and run:",
        "// go generate ./internal/providers/all",
        "package all",
        "",
        "import (",
    ]
    lines += ['\t_ "%s/internal/providers/%s"' % (module, name) for name in adapters(root)]
    lines += [")"]
    return "\n".join(lines) + "\n"


def write(root):
    text = generate(root)
    path = os.path.join(root, OUTPUT)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    print("wrote: %s" % OUTPUT)
    return 0


def check(root):
    text = generate(root)
    try:
        with open(os.path.join(root, OUTPUT), encoding="utf-8", newline="") as handle:
            on_disk = handle.read()
    except OSError:
        on_disk = None
    if on_disk == text:
        print("current: %s" % OUTPUT)
        return 0
    if on_disk is None:
        print("%s does not exist" % OUTPUT)
    else:
        for line in difflib.unified_diff(on_disk.splitlines(), text.splitlines(), "on disk", "generated", lineterm="", n=0):
            print(line[:240])
    print("stale: %s. Run: python3 %s  and commit that file." % (OUTPUT, SCRIPT))
    return 1


# ---------------------------------------------------------------------------
# Self-test: every rule is shown on a throw-away tree, and the check is shown to fail.

def put(root, relative, text):
    path = os.path.join(root, relative)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)


def self_test():
    failures = []

    def case(name, ok):
        print("%s  %s" % ("ok  " if ok else "FAIL", name))
        if not ok:
            failures.append(name)

    def input_error(root, needle):
        try:
            generate(root)
        except InputError as error:
            return needle in str(error)
        return False

    with tempfile.TemporaryDirectory() as root:
        put(root, API + "/go.mod", "module example.com/api\n\ngo 1.26.0\n")
        put(root, PROVIDERS + "/provider.go", "package providers\n")
        put(root, PROVIDERS + "/beta/provider.go", "package beta\n")
        put(root, PROVIDERS + "/alpha/provider.go", "package alpha\n")
        put(root, PROVIDERS + "/conformance/conformance_test.go", "package conformance\n")
        put(root, PROVIDERS + "/all/gen.go", "package all\n")
        text = generate(root)
        imports = [line for line in text.splitlines() if line.startswith('\t_ "')]
        case("the first line marks the file as generated",
             text.splitlines()[0] == "// Code generated by %s. DO NOT EDIT." % SCRIPT)
        case("every adapter folder is imported once, sorted by name",
             imports == ['\t_ "example.com/api/internal/providers/alpha"', '\t_ "example.com/api/internal/providers/beta"'])
        case("a folder without provider.go, and all/ itself, is not imported",
             not [line for line in imports if line.endswith(('/conformance"', '/all"'))])

        write(root)
        case("--check passes on a fresh output", check(root) == 0)
        put(root, PROVIDERS + "/gamma/provider.go", "package gamma\n")
        case("a new adapter folder makes the file stale", check(root) == 1)
        write(root)
        case("the new adapter is imported after a write", "providers/gamma" in generate(root) and check(root) == 0)
        os.remove(os.path.join(root, OUTPUT))
        case("--check fails when the file does not exist", check(root) == 1)

        put(root, PROVIDERS + "/Bad_Name/provider.go", "package bad\n")
        case("a folder name that is not a pack name is an error", input_error(root, "Bad_Name: the folder name"))
        os.remove(os.path.join(root, PROVIDERS, "Bad_Name", "provider.go"))

        for name in ("alpha", "beta", "gamma"):
            os.remove(os.path.join(root, PROVIDERS, name, "provider.go"))
        case("a tree with no adapter is an error", input_error(root, "no folder holds a provider.go"))

        put(root, API + "/go.mod", "go 1.26.0\n")
        case("a go.mod without a module line is an error", input_error(root, "has no module line"))
        os.remove(os.path.join(root, API, "go.mod"))
        case("a missing go.mod is an error", input_error(root, "go.mod: cannot be read"))

    if failures:
        print("self-test: %d case(s) FAILED" % len(failures))
        return 1
    print("self-test: all cases passed")
    return 0


def main(argv):
    root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    if argv == ["--self-test"]:
        return self_test()
    if argv not in ([], ["--check"]):
        sys.stderr.write("usage: python3 %s [--check | --self-test]\n" % SCRIPT)
        return 2
    try:
        return check(root) if argv else write(root)
    except InputError as error:
        sys.stderr.write("%s: %s\n" % (SCRIPT, error))
        return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
