#!/usr/bin/env python3
"""slots.py - the inventory of the bootstrap kit slots, generated from the tree.

It reads   clusters/_template/bootstrap-kit/kustomization.yaml   (the order of the slots)
           clusters/_template/bootstrap-kit/<NN>*.yaml           (one slot file each)
           scripts/expected-bootstrap-deps.yaml                  (the declared dependencies)
It writes  docs/generated/bootstrap-slots.md

Usage, from any directory:
  python3 scripts/generators/slots.py              write the file
  python3 scripts/generators/slots.py --check      write nothing; exit 1 when the file on disk differs
  python3 scripts/generators/slots.py --self-test  prove every rule on a throw-away tree

Exit codes: 0 done or current; 1 the file is stale, or a self-test case failed;
2 an input is missing or cannot be read.

The output carries no chart version. CI writes versions on main without a pull
request, and this file must not go stale when it does.
"""
import difflib
import os
import re
import sys
import tempfile

try:
    import yaml
except ImportError:
    sys.stderr.write("slots.py needs PyYAML: pip install pyyaml\n")
    sys.exit(2)

SCRIPT = "scripts/generators/slots.py"
OUTPUT = "docs/generated/bootstrap-slots.md"
KIT = "clusters/_template/bootstrap-kit"
EXPECTED = "scripts/expected-bootstrap-deps.yaml"
SLOT_FILE = re.compile(r"^[0-9][^/]*\.yaml$")


class InputError(Exception):
    """An input is missing or does not have the shape this generator reads."""


def load_documents(root, relative):
    path = os.path.join(root, relative)
    try:
        with open(path, encoding="utf-8") as handle:
            return [d for d in yaml.safe_load_all(handle) if d is not None]
    except OSError as error:
        raise InputError("%s: cannot be read: %s" % (relative, error.strerror))
    except yaml.YAMLError as error:
        raise InputError("%s: is not valid YAML: %s" % (relative, str(error).splitlines()[0]))


def cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def code(text):
    return "`%s`" % str(text).replace("`", "'")


def helm_releases(root, name):
    relative = "%s/%s" % (KIT, name)
    found = []
    for document in load_documents(root, relative):
        if isinstance(document, dict) and document.get("kind") == "HelmRelease":
            found.append(document)
    return found


def text_or_dash(value):
    return "-" if value in (None, "") else cell(value)


def depends_on(release):
    names = []
    for item in (release.get("spec") or {}).get("dependsOn") or []:
        if isinstance(item, dict) and item.get("name"):
            names.append(str(item["name"]))
    return names


def show(value):
    if isinstance(value, bool):
        return "true" if value else "false"
    return str(value)


def switches(release):
    """spec.suspend and spec.values.enabled, whatever they hold; and
    spec.values.<key>.enabled when a substitution variable sets it."""
    spec = release.get("spec") or {}
    found = []
    if "suspend" in spec:
        found.append("suspend=%s" % show(spec["suspend"]))
    values = spec.get("values")
    if isinstance(values, dict):
        if "enabled" in values:
            found.append("values.enabled=%s" % show(values["enabled"]))
        for key, value in values.items():
            if isinstance(value, dict) and "enabled" in value:
                inner = value["enabled"]
                if isinstance(inner, str) and "${" in inner:
                    found.append("values.%s.enabled=%s" % (key, inner))
    return found


def expected_entries(root):
    documents = load_documents(root, EXPECTED)
    if len(documents) != 1 or not isinstance(documents[0], dict) or not isinstance(documents[0].get("slots"), list):
        raise InputError("%s: has no list under the key slots" % EXPECTED)
    entries = []
    for entry in documents[0]["slots"]:
        if not isinstance(entry, dict) or not entry.get("name"):
            raise InputError("%s: an entry of slots has no name" % EXPECTED)
        entries.append(entry)
    return entries


def generate(root):
    documents = load_documents(root, "%s/kustomization.yaml" % KIT)
    if len(documents) != 1 or not isinstance(documents[0], dict) or not isinstance(documents[0].get("resources"), list):
        raise InputError("%s/kustomization.yaml: has no list under the key resources" % KIT)
    registered = [str(name) for name in documents[0]["resources"]]
    try:
        on_disk = sorted(name for name in os.listdir(os.path.join(root, KIT)) if SLOT_FILE.match(name))
    except OSError as error:
        raise InputError("%s: cannot be listed: %s" % (KIT, error.strerror))
    expected = expected_entries(root)
    expected_by_name = {str(entry["name"]): entry for entry in expected}

    lines = [
        "Generated by %s. Do not edit." % SCRIPT,
        "",
        "# Bootstrap slots",
        "",
        "The slots of the bootstrap kit, `%s/`. A slot is one file of that folder." % KIT,
        "To change this file, change an input and run `python3 %s`." % SCRIPT,
        "The check `generated-docs` fails a pull request in which this file is stale.",
        "This file carries no chart version: CI writes versions, and this file does not change when CI does.",
        "",
        "## Registered slots",
        "",
        "One row for each HelmRelease of each file that `%s/kustomization.yaml` lists, in the order of that list." % KIT,
        "",
        "- Slot: the file name up to its first dash.",
        "- Switches: the value of `spec.suspend` and of `spec.values.enabled` when the slot sets it, and each `spec.values.<key>.enabled` that a substitution variable sets.",
        "- Expected dependencies: `same` when the entry of this HelmRelease in `%s` names the same set as Depends on; `differs` when it names another set; `not declared` when there is no entry." % EXPECTED,
        "",
        "| Slot | File | HelmRelease | Release name | Target namespace | Chart | Depends on | Switches | Expected dependencies |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    present = set()
    for name in registered:
        if "/" in name or not name.endswith(".yaml"):
            lines.append("| - | %s | (not a file of this folder) | - | - | - | - | - | - |" % cell(name))
            continue
        releases = helm_releases(root, name)
        slot = name.split("-", 1)[0].split(".", 1)[0]
        if not releases:
            lines.append("| %s | %s | (none) | - | - | - | - | - | - |" % (cell(slot), cell(name)))
        for release in releases:
            metadata = release.get("metadata") or {}
            spec = release.get("spec") or {}
            release_name = str(metadata.get("name") or "")
            if not release_name:
                raise InputError("%s/%s: a HelmRelease has no metadata.name" % (KIT, name))
            present.add(release_name)
            chart = ((spec.get("chart") or {}).get("spec") or {}).get("chart")
            needs = depends_on(release)
            entry = expected_by_name.get(release_name)
            if entry is None:
                verdict = "not declared"
            elif set(str(x) for x in entry.get("depends_on") or []) == set(needs):
                verdict = "same"
            else:
                verdict = "differs"
            found = switches(release)
            lines.append("| %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (
                cell(slot), cell(name), cell(release_name),
                text_or_dash(spec.get("releaseName")), text_or_dash(spec.get("targetNamespace")),
                text_or_dash(chart),
                cell(", ".join(needs)) if needs else "-",
                cell(", ".join(code(x) for x in found)) if found else "-",
                verdict))

    lines += ["", "## Slot files that the kustomization does not list", ""]
    unlisted = [name for name in on_disk if name not in registered]
    if unlisted:
        lines += [
            "Flux never applies these files.",
            "",
            "| File | HelmRelease |",
            "|---|---|",
        ]
        for name in unlisted:
            names = []
            for release in helm_releases(root, name):
                release_name = str((release.get("metadata") or {}).get("name") or "")
                if release_name:
                    names.append(release_name)
                    present.add(release_name)
            lines.append("| %s | %s |" % (cell(name), cell(", ".join(names)) if names else "(none)"))
    else:
        lines.append("None.")

    lines += ["", "## Declared without a slot file", ""]
    absent = [entry for entry in expected if str(entry["name"]) not in present]
    if absent:
        lines += [
            "Entries of `%s` whose HelmRelease is in no slot file. Nothing installs them." % EXPECTED,
            "",
            "| Slot | HelmRelease | Depends on | Wave |",
            "|---|---|---|---|",
        ]
        for entry in absent:
            needs = [str(x) for x in entry.get("depends_on") or []]
            lines.append("| %s | %s | %s | %s |" % (
                text_or_dash(entry.get("slot")), cell(entry["name"]),
                cell(", ".join(needs)) if needs else "-", text_or_dash(entry.get("wave"))))
    else:
        lines.append("None.")
    return "\n".join(lines) + "\n"


def write(root):
    text = generate(root)
    path = os.path.join(root, OUTPUT)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    print("wrote: %s" % OUTPUT)
    return 0


def check(root):
    text = generate(root)
    try:
        with open(os.path.join(root, OUTPUT), encoding="utf-8", newline="") as handle:
            on_disk = handle.read()
    except OSError:
        on_disk = None
    if on_disk == text:
        print("current: %s" % OUTPUT)
        return 0
    if on_disk is None:
        print("%s does not exist" % OUTPUT)
    else:
        diff = list(difflib.unified_diff(on_disk.splitlines(), text.splitlines(), "on disk", "generated", lineterm="", n=0))
        for line in diff[:30]:
            print(line[:240])
        if len(diff) > 30:
            print("... %d more lines of difference" % (len(diff) - 30))
    print("stale: %s. Run: python3 %s  and commit that file." % (OUTPUT, SCRIPT))
    return 1


# ---------------------------------------------------------------------------
# Self-test: every rule is shown on a throw-away tree, and the check is shown to fail.

SLOT = """---
apiVersion: v1
kind: Namespace
metadata:
  name: %(namespace)s
---
apiVersion: helm.toolkit.fluxcd.io/v2
kind: HelmRelease
metadata:
  name: %(name)s
  namespace: flux-system
spec:
%(extra)s  releaseName: %(release)s
  targetNamespace: %(namespace)s
%(depends)s  chart:
    spec:
      chart: %(name)s
      version: %(version)s
"""


def put(root, relative, text):
    path = os.path.join(root, relative)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(text)


def slot_text(name, release, namespace, version="1.0.0", depends=(), extra=""):
    block = ""
    if depends:
        block = "  dependsOn:\n" + "".join("    - name: %s\n      namespace: flux-system\n" % d for d in depends)
    return SLOT % {"name": name, "release": release, "namespace": namespace, "version": version,
                   "depends": block, "extra": extra}


def fixture(root):
    put(root, KIT + "/kustomization.yaml",
        "apiVersion: kustomize.config.k8s.io/v1beta1\nkind: Kustomization\nresources:\n"
        "  # the order here is not the order of the names\n  - 02-second.yaml\n  - 01-first.yaml\n")
    put(root, KIT + "/01-first.yaml", slot_text("bp-first", "first", "first-system"))
    put(root, KIT + "/02-second.yaml", slot_text(
        "bp-second", "second", "second-system", depends=("bp-first",),
        extra="  suspend: ${SECOND_SUSPEND:=false}\n  values:\n    enabled: false\n    part:\n      enabled: ${PART_ENABLED:-true}\n    other:\n      enabled: true\n"))
    put(root, KIT + "/03-third.yaml", slot_text("bp-third", "third", "third-system"))
    put(root, KIT + "/placement.yaml", "kind: PlacementTable\n")
    put(root, EXPECTED,
        "slots:\n"
        "  - slot: 1\n    name: bp-first\n    depends_on: []\n    wave: present\n"
        "  - slot: 2\n    name: bp-second\n    depends_on: [bp-first]\n    wave: present\n"
        "  - slot: \"40\"\n    name: bp-later\n    depends_on: [bp-first, bp-second]\n    wave: W9\n")


def self_test():
    failures = []

    def case(name, ok):
        print("%s  %s" % ("ok  " if ok else "FAIL", name))
        if not ok:
            failures.append(name)

    def fails_with_input_error(root):
        try:
            generate(root)
        except InputError:
            return True
        return False

    with tempfile.TemporaryDirectory() as root:
        fixture(root)
        text = generate(root)
        rows = [line for line in text.splitlines() if line.startswith("| ")]
        case("the first line says who generates the file",
             text.splitlines()[0] == "Generated by scripts/generators/slots.py. Do not edit.")
        case("rows follow the order of the kustomization, not the order of the names",
             text.index("| 02 | 02-second.yaml |") < text.index("| 01 | 01-first.yaml |"))
        case("a row carries the release name, the namespace, the chart and the dependencies",
             "| 02 | 02-second.yaml | bp-second | second | second-system | bp-second | bp-first |" in text)
        case("a slot without dependencies shows a dash",
             "| 01 | 01-first.yaml | bp-first | first | first-system | bp-first | - | - | same |" in text)
        case("the switches are suspend, values.enabled and a variable one level down; a literal one level down is left out",
             "| `suspend=${SECOND_SUSPEND:=false}`, `values.enabled=false`, `values.part.enabled=${PART_ENABLED:-true}` | same |" in text)
        case("a slot file that the kustomization does not list is in the second table",
             "| 03-third.yaml | bp-third |" in text and "| 03 | 03-third.yaml |" not in text)
        case("an entry of the expected file whose HelmRelease is in no slot file is in the third table",
             "| 40 | bp-later | bp-first, bp-second | W9 |" in text)
        case("a file that is no slot file is not listed", "placement.yaml" not in text)
        case("three tables: 2 + 1 + 1 rows and three header rows", len(rows) == 7)

        write(root)
        case("--check passes on a fresh output", check(root) == 0)

        put(root, KIT + "/01-first.yaml", slot_text("bp-first", "first", "first-system", version="9.9.9"))
        case("a changed chart version changes nothing", generate(root) == text and check(root) == 0)

        put(root, KIT + "/01-first.yaml", slot_text("bp-first", "first", "first-system", depends=("bp-second",)))
        changed = generate(root)
        case("a changed dependency changes the row and reads differs",
             "| 01 | 01-first.yaml | bp-first | first | first-system | bp-first | bp-second | - | differs |" in changed)
        case("--check fails when the file on disk is stale", check(root) == 1)

        os.remove(os.path.join(root, OUTPUT))
        case("--check fails when the file does not exist", check(root) == 1)

        put(root, EXPECTED, "slots:\n  - slot: 2\n    name: bp-second\n    depends_on: [bp-first]\n    wave: present\n")
        case("no entry in the expected file reads not declared",
             "| bp-first | bp-second | - | not declared |" in generate(root)
             and generate(root).rstrip().endswith("## Declared without a slot file\n\nNone."))

        put(root, KIT + "/kustomization.yaml", "resources:\n  - 01-first.yaml\n  - ../elsewhere\n")
        case("an entry of the kustomization that is not a file of the folder gets a row that says so",
             "| - | ../elsewhere | (not a file of this folder) | - | - | - | - | - | - |" in generate(root))

        put(root, KIT + "/kustomization.yaml", "resources:\n  - 01-first.yaml\n  - 09-missing.yaml\n")
        case("a listed slot file that does not exist is an input error", fails_with_input_error(root))

        put(root, KIT + "/kustomization.yaml", "resources: nothing\n")
        case("a kustomization without a resources list is an input error", fails_with_input_error(root))

        put(root, KIT + "/kustomization.yaml", "resources:\n  - 01-first.yaml\n")
        put(root, KIT + "/01-first.yaml", "kind: HelmRelease\nmetadata: [broken\n")
        case("a slot file that is not valid YAML is an input error", fails_with_input_error(root))

        put(root, KIT + "/01-first.yaml", slot_text("bp-first", "first", "first-system"))
        os.remove(os.path.join(root, EXPECTED))
        case("a missing expected file is an input error", fails_with_input_error(root))

    if failures:
        print("self-test: %d case(s) FAILED" % len(failures))
        return 1
    print("self-test: all cases passed")
    return 0


def main(argv):
    root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    if argv == ["--self-test"]:
        return self_test()
    if argv not in ([], ["--check"]):
        sys.stderr.write("usage: python3 %s [--check | --self-test]\n" % SCRIPT)
        return 2
    try:
        return check(root) if argv else write(root)
    except InputError as error:
        sys.stderr.write("%s: %s\n" % (SCRIPT, error))
        return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
