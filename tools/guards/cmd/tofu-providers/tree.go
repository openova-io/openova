// The files this command reads and writes, relative to the repository root.
const (
	listPath        = "clusters/_template/infrastructure/providers/base/opentofu-providers.yaml"
	packsDir        = "infra/providers"
	packListName    = "tofu-providers.txt"
	compositionPath = "platform/crossplane-claims/chart/templates/compositions/cloudadoption.yaml"
	defaultHost     = "registry.opentofu.org"
	writerScript    = "tools/guards/cmd/tofu-providers/write-list.sh"
)

// lineRE is one line of a list: source, version, index digest.
var lineRE = regexp.MustCompile(`^(registry\.opentofu\.org/[a-z0-9-]+/[a-z0-9-]+) ([0-9]+\.[0-9]+\.[0-9]+) (sha256:[0-9a-f]{64})$`)

// entry is one listed package.
type entry struct {
	source, digest string
	version        version
}

func (e entry) String() string { return e.source + " " + e.version.String() + " " + e.digest }

// parseLines reads list lines; lineNo is the number of the first line in its file.
// Every line that is not of the form of lineRE, and every source listed twice, is a
// problem naming the file and the line.
func parseLines(file string, lines []string, lineNo []int) ([]entry, []string) {
	var out []entry
	var problems []string
	seen := map[string]int{}
	for i, l := range lines {
		m := lineRE.FindStringSubmatch(l)
		if m == nil {
			problems = append(problems, fmt.Sprintf("%s:%d: %q is not <registry.opentofu.org/namespace/type> <major.minor.patch> <sha256: and 64 hex digits>", file, lineNo[i], l))
			continue
		}
		v, _, err := parseVersion(m[2])
		if err != nil {
			problems = append(problems, fmt.Sprintf("%s:%d: %v", file, lineNo[i], err))
			continue
		}
		if first, ok := seen[m[1]]; ok {
			problems = append(problems, fmt.Sprintf("%s:%d: %s is listed twice (first at line %d); a source has one version", file, lineNo[i], m[1], first))
			continue
		}
		seen[m[1]] = lineNo[i]
		out = append(out, entry{source: m[1], version: v, digest: m[3]})
	}
	return out, problems
}

func readLines(path string) ([]string, error) {
	b, err := os.ReadFile(filepath.Clean(path))
	if err != nil {
		return nil, err
	}
	return strings.Split(strings.TrimRight(string(b), "\n"), "\n"), nil
}

// readPackList reads infra/providers/<pack>/tofu-providers.txt: list lines, with
// blank lines and lines starting with # left out. A pack without the file lists
// nothing.
func readPackList(root, rel string) ([]entry, []string, error) {
	lines, err := readLines(filepath.Join(root, rel))
	if os.IsNotExist(err) {
		return nil, nil, nil
	}
	if err != nil {
		return nil, nil, err
	}
	var keep []string
	var nos []int
	for i, l := range lines {
		t := strings.TrimSpace(l)
		if t == "" || strings.HasPrefix(t, "#") {
			continue
		}
		keep, nos = append(keep, t), append(nos, i+1)
	}
	e, p := parseLines(rel, keep, nos)
	return e, p, nil
}

var blockKeyRE = regexp.MustCompile(`^(\s*)providers:\s*\|[-+]?\s*$`)

// readListFile reads the list of the ConfigMap opentofu-providers: the lines of
// the block scalar data.providers.
func readListFile(root string) ([]entry, []string, error) {
	lines, err := readLines(filepath.Join(root, listPath))
	if err != nil {
		return nil, nil, err
	}
	start, indent := -1, 0
	for i, l := range lines {
		if m := blockKeyRE.FindStringSubmatch(l); m != nil {
			start, indent = i+1, len(m[1])
			break
		}
	}
	if start < 0 {
		return nil, nil, fmt.Errorf("%s holds no block scalar providers: |", listPath)
	}
	var keep []string
	var nos []int
	for i := start; i < len(lines); i++ {
		l := lines[i]
		if strings.TrimSpace(l) == "" {
			continue
		}
		if len(l)-len(strings.TrimLeft(l, " ")) <= indent {
			break
		}
		keep, nos = append(keep, strings.TrimSpace(l)), append(nos, i+1)
	}
	e, p := parseLines(listPath, keep, nos)
	return e, p, nil
}

// renderList is the ConfigMap that write-list.sh writes from the union of the
// packs' lists, sorted by source.
func renderList(union []entry) string {
	sort.Slice(union, func(i, j int) bool { return union[i].source < union[j].source })
	var b strings.Builder
	b.WriteString(`# generated by bash ` + writerScript + ` from the file
# ` + packListName + ` of every provider pack under ` + packsDir + `; never edit it by hand.
#
# crossplane-system/opentofu-providers (SOV-342): the OpenTofu provider packages the
# OCI provider mirror holds, one line each: source address, version, digest of the
# package's OCI index. The workflow mirror-tofu-providers publishes each one at
# ghcr.io/openova-io/tofu-providers/<namespace>/<type>:<version> before the change
# that lists it merges, and fails when a digest it builds or finds there differs.
# The provider pod installs providers only from that mirror (opentofu-cli-config.yaml);
# a version that is not listed is not installed, never fetched from the public registry.
apiVersion: v1
kind: ConfigMap
metadata:
  name: opentofu-providers
  namespace: crossplane-system
  labels:
    catalyst.openova.io/component: crossplane
data:
  providers: |
`)
	for _, e := range union {
		b.WriteString("    " + e.String() + "\n")
	}
	return b.String()
}

// pack is one provider pack: infra/providers/<name> with a pack.yaml.
type pack struct {
	name, dir string
}

func readPacks(root string) ([]pack, error) {
	ents, err := os.ReadDir(filepath.Join(root, packsDir))
	if err != nil {
		return nil, err
	}
	var out []pack
	for _, e := range ents {
		if !e.IsDir() {
			continue
		}
		dir := packsDir + "/" + e.Name()
		if _, err := os.Stat(filepath.Join(root, dir, "pack.yaml")); err == nil {
			out = append(out, pack{name: e.Name(), dir: dir})
		}
	}
	if len(out) == 0 {
		return nil, fmt.Errorf("no %s/<pack>/pack.yaml found", packsDir)
	}
	return out, nil
}

// union merges the packs' lists. Two packs that list one source with another
// version or digest are a problem.
func union(lists map[string][]entry) ([]entry, []string) {
	var names []string
	for n := range lists {
		names = append(names, n)
	}
	sort.Strings(names)
	by := map[string]entry{}
	from := map[string]string{}
	var problems []string
	for _, n := range names {
		for _, e := range lists[n] {
			if have, ok := by[e.source]; ok {
				if have != e {
					problems = append(problems, fmt.Sprintf("%s lists %s and %s lists %s: one source has one version and one digest", from[e.source], have, n, e))
				}
				continue
			}
			by[e.source], from[e.source] = e, n
		}
	}
	var out []entry
	for _, e := range by {
		out = append(out, e)
	}
	sort.Slice(out, func(i, j int) bool { return out[i].source < out[j].source })
	return out, problems
}

// packLists reads every pack's list.
func packLists(root string, packs []pack) (map[string][]entry, []string, error) {
	lists := map[string][]entry{}
	var problems []string
	for _, p := range packs {
		e, pr, err := readPackList(root, p.dir+"/"+packListName)
		if err != nil {
			return nil, nil, err
		}
		lists[p.dir+"/"+packListName], problems = e, append(problems, pr...)
	}
	return lists, problems, nil
}

// requirement is one entry of a required_providers block.
type requirement struct {
	file, name, source, constraint string
}

var keywordRE = regexp.MustCompile(`\brequired_providers\s*\{`)

// stripComments blanks # and // comments and /* */ blocks outside double-quoted
// strings; a string ends at the end of its line at the latest.
func stripComments(s string) string {
	out := []byte(s)
	inStr, inBlock := false, false
	for i := 0; i < len(out); i++ {
		c := out[i]
		switch {
		case inBlock:
			if c == '*' && i+1 < len(out) && out[i+1] == '/' {
				out[i], out[i+1] = ' ', ' '
				i++
				inBlock = false
			} else if c != '\n' {
				out[i] = ' '
			}
		case inStr:
			if c == '\\' && i+1 < len(out) && out[i+1] != '\n' {
				i++
			} else if c == '"' || c == '\n' {
				inStr = false
			}
		case c == '"':
			inStr = true
		case c == '#' || (c == '/' && i+1 < len(out) && out[i+1] == '/'):
			for i < len(out) && out[i] != '\n' {
				out[i] = ' '
				i++
			}
		case c == '/' && i+1 < len(out) && out[i+1] == '*':
			out[i], out[i+1] = ' ', ' '
			i++
			inBlock = true
		}
	}
	return string(out)
}

type token struct {
	kind byte // 'i' identifier, 's' string, or the punctuation character itself
	text string
}

func tokenize(s string) []token {
	var out []token
	for i := 0; i < len(s); {
		c := s[i]
		switch {
		case c == '"':
			j := i + 1
			for j < len(s) && s[j] != '"' && s[j] != '\n' {
				if s[j] == '\\' {
					j++
				}
				j++
			}
			if j > len(s) {
				j = len(s)
			}
			out = append(out, token{'s', s[i+1 : j]})
			i = j + 1
		case c == '_' || c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z':
			j := i
			for j < len(s) && (s[j] == '_' || s[j] == '-' || s[j] >= 'a' && s[j] <= 'z' || s[j] >= 'A' && s[j] <= 'Z' || s[j] >= '0' && s[j] <= '9') {
				j++
			}
			out = append(out, token{'i', s[i:j]})
			i = j
		case strings.IndexByte("{}[]=,", c) >= 0:
			out = append(out, token{c, string(c)})
			i++
		default:
			i++
		}
	}
	return out
}

// skipValue returns the index after the value that starts at i: a string, an
// identifier, or a balanced { } or [ ] group.
func skipValue(t []token, i int) int {
	if i >= len(t) {
		return i
	}
	if t[i].kind != '{' && t[i].kind != '[' {
		return i + 1
	}
	depth := 0
	for ; i < len(t); i++ {
		switch t[i].kind {
		case '{', '[':
			depth++
		case '}', ']':
			depth--
			if depth == 0 {
				return i + 1
			}
		}
	}
	return i
}

// normalize writes a source address with its host: ns/type becomes
// registry.opentofu.org/ns/type.
func normalize(source string) string {
	s := strings.ToLower(strings.TrimSpace(source))
	if strings.Count(s, "/") == 1 {
		return defaultHost + "/" + s
	}
	return s
}

// requiredProviders reads every required_providers block of an OpenTofu text
// (a module file, or a file that holds an inline module).
func requiredProviders(file, text string) []requirement {
	clean := stripComments(text)
	var out []requirement
	for _, loc := range keywordRE.FindAllStringIndex(clean, -1) {
		body := tokenize(clean[loc[1]:])
		// body starts inside the block's brace; read entries until its closing brace.
		for i := 0; i < len(body); {
			if body[i].kind == '}' {
				break
			}
			if body[i].kind != 'i' || i+2 >= len(body) || body[i+1].kind != '=' {
				i = skipValue(body, i)
				continue
			}
			r := requirement{file: file, name: body[i].text}
			switch v := body[i+2]; v.kind {
			case 's':
				r.constraint = v.text
				i += 3
			case '{':
				end := skipValue(body, i+2)
				attrs := body[i+3 : end-1]
				for j := 0; j < len(attrs); {
					if attrs[j].kind == 'i' && j+2 < len(attrs) && attrs[j+1].kind == '=' {
						if attrs[j+2].kind == 's' {
							switch attrs[j].text {
							case "source":
								r.source = attrs[j+2].text
							case "version":
								r.constraint = attrs[j+2].text
							}
						}
						j = skipValue(attrs, j+2)
						continue
					}
					j++
				}
				i = end
			default:
				i = skipValue(body, i+2)
			}
			if r.source == "" {
				r.source = "hashicorp/" + r.name
			}
			r.source = normalize(r.source)
			out = append(out, r)
		}
	}
	return out
}

var skipDirs = map[string]bool{"tests": true, "testdata": true, ".terraform": true, "examples": true}

// moduleFiles walks a pack folder for its *.tf files and lock files, leaving out
// test folders.
func moduleFiles(root, dir string) (tf, locks []string, err error) {
	err = filepath.WalkDir(filepath.Join(root, dir), func(p string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			if skipDirs[d.Name()] {
				return filepath.SkipDir
			}
			return nil
		}
		rel, _ := filepath.Rel(root, p)
		rel = filepath.ToSlash(rel)
		switch {
		case strings.HasSuffix(d.Name(), ".tf"):
			tf = append(tf, rel)
		case d.Name() == ".terraform.lock.hcl":
			locks = append(locks, rel)
		}
		return nil
	})
	return tf, locks, err
}

var lockProviderRE = regexp.MustCompile(`^provider\s+"([^"]+)"\s*\{`)
var lockVersionRE = regexp.MustCompile(`^\s*version\s*=\s*"([^"]+)"`)

// lockPins reads the provider "<source>" { version = "<v>" } blocks of a lock file.
func lockPins(root, rel string) (map[string]string, error) {
	f, err := os.Open(filepath.Clean(filepath.Join(root, rel)))
	if err != nil {
		return nil, err
	}
	defer func() { _ = f.Close() }()
	pins := map[string]string{}
	cur := ""
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		l := sc.Text()
		if m := lockProviderRE.FindStringSubmatch(l); m != nil {
			cur = normalize(m[1])
			continue
		}
		if m := lockVersionRE.FindStringSubmatch(l); m != nil && cur != "" {
			pins[cur] = m[1]
			cur = ""
		}
	}
	return pins, sc.Err()
}

var sourceItemRE = regexp.MustCompile(`source:\s*["']?([^"',}\s]+)`)

// packSources reads spec.tofuProviders[].source of a pack.yaml, in block or flow form.
func packSources(root, rel string) ([]string, error) {
	lines, err := readLines(filepath.Join(root, rel))
	if err != nil {
		return nil, err
	}
	var out []string
	key := -1
	for _, l := range lines {
		indent := len(l) - len(strings.TrimLeft(l, " "))
		t := strings.TrimSpace(l)
		if key < 0 {
			if strings.HasPrefix(t, "tofuProviders:") {
				key = indent
				for _, m := range sourceItemRE.FindAllStringSubmatch(t, -1) {
					out = append(out, normalize(m[1]))
				}
			}
			continue
		}
		if t == "" || strings.HasPrefix(t, "#") {
			continue
		}
		if indent <= key && !strings.HasPrefix(t, "- ") || indent < key {
			break
		}
		for _, m := range sourceItemRE.FindAllStringSubmatch(t, -1) {
			out = append(out, normalize(m[1]))
		}
	}
	return out, nil
}

// checkConstraints judges requirements against a list.
func checkConstraints(reqs []requirement, listed map[string]entry, listName string) []string {
	var out []string
	for _, r := range reqs {
		e, ok := listed[r.source]
		if !ok {
			out = append(out, fmt.Sprintf("%s: %s requires %s %q; %s does not list it", r.file, r.name, r.source, r.constraint, listName))
			continue
		}
		if r.constraint == "" {
			continue
		}
		terms, err := parseConstraint(r.constraint)
		if err != nil {
			out = append(out, fmt.Sprintf("%s: %s requires %s: %v", r.file, r.name, r.source, err))
			continue
		}
		if !meets(e.version, terms) {
			out = append(out, fmt.Sprintf("%s: %s requires %s %q; %s lists %s, which does not meet it", r.file, r.name, r.source, r.constraint, listName, e.version))
		}
	}
	return out
}

func byS(es []entry) map[string]entry {
	m := map[string]entry{}
	for _, e := range es {
		m[e.source] = e
	}
	return m
}

// result is what check found and how much it read.
type result struct {
	findings                   []string
	listed, requirements, pins int
}

// check judges the tree at root. An error means the tree could not be read.
func check(root string) (result, error) {
	var res result
	packs, err := readPacks(root)
	if err != nil {
		return res, err
	}
	shared, problems, err := readListFile(root)
	if err != nil {
		return res, err
	}
	res.findings = append(res.findings, problems...)
	res.listed = len(shared)
	lists, problems, err := packLists(root, packs)
	if err != nil {
		return res, err
	}
	res.findings = append(res.findings, problems...)
	all, problems := union(lists)
	res.findings = append(res.findings, problems...)
	want := renderList(all)
	have, err := os.ReadFile(filepath.Clean(filepath.Join(root, listPath)))
	if err != nil {
		return res, err
	}
	if string(have) != want {
		res.findings = append(res.findings, fmt.Sprintf("%s is not what %s writes from the packs' %s files; run: bash %s", listPath, writerScript, packListName, writerScript))
	}
	sharedBy := byS(shared)
	comp, err := os.ReadFile(filepath.Clean(filepath.Join(root, compositionPath)))
	if err != nil {
		return res, err
	}
	reqs := requiredProviders(compositionPath, string(comp))
	if len(reqs) == 0 {
		return res, fmt.Errorf("%s holds no required_providers block", compositionPath)
	}
	res.requirements += len(reqs)
	res.findings = append(res.findings, checkConstraints(reqs, sharedBy, listPath)...)
	for _, p := range packs {
		own := p.dir + "/" + packListName
		ownBy := byS(lists[own])
		tf, locks, err := moduleFiles(root, p.dir)
		if err != nil {
			return res, err
		}
		for _, f := range tf {
			b, err := os.ReadFile(filepath.Clean(filepath.Join(root, f)))
			if err != nil {
				return res, err
			}
			reqs := requiredProviders(f, string(b))
			res.requirements += len(reqs)
			res.findings = append(res.findings, checkConstraints(reqs, ownBy, own)...)
		}
		for _, l := range locks {
			pins, err := lockPins(root, l)
			if err != nil {
				return res, err
			}
			var srcs []string
			for s := range pins {
				srcs = append(srcs, s)
			}
			sort.Strings(srcs)
			for _, s := range srcs {
				res.pins++
				e, ok := ownBy[s]
				if !ok || e.version.String() != pins[s] {
					res.findings = append(res.findings, fmt.Sprintf("%s pins %s %s; %s does not list that version", l, s, pins[s], own))
				}
			}
		}
		sources, err := packSources(root, p.dir+"/pack.yaml")
		if err != nil {
			return res, err
		}
		for _, s := range sources {
			if _, ok := ownBy[s]; !ok {
				res.findings = append(res.findings, fmt.Sprintf("%s/pack.yaml names %s in spec.tofuProviders; %s does not list it", p.dir, s, own))
			}
		}
	}
	return res, nil
}

// writeList writes the ConfigMap from the packs' lists, or with checkOnly reports
// whether the file on disk differs.
func writeList(root string, checkOnly bool) (changed bool, problems []string, err error) {
	packs, err := readPacks(root)
	if err != nil {
		return false, nil, err
	}
	lists, problems, err := packLists(root, packs)
	if err != nil {
		return false, nil, err
	}
	all, more := union(lists)
	problems = append(problems, more...)
	if len(problems) > 0 {
		return false, problems, nil
	}
	want := renderList(all)
	have, err := os.ReadFile(filepath.Clean(filepath.Join(root, listPath)))
	if err != nil && !os.IsNotExist(err) {
		return false, nil, err
	}
	if string(have) == want {
		return false, nil, nil
	}
	if checkOnly {
		return true, nil, nil
	}
	if err := os.MkdirAll(filepath.Dir(filepath.Join(root, listPath)), 0o750); err != nil {
		return false, nil, err
	}
	return true, nil, os.WriteFile(filepath.Join(root, listPath), []byte(want), 0o600)
}
