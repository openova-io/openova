#!/usr/bin/env bash
# SOV-132 — step 04's registry-pivot DaemonSet touches only the containerd
# certs.d files it wrote itself.
#
# Measured 20 Nov 2026 on a fresh two-region install, region a, in Phase 1: the
# DaemonSet (installed at first boot) logged `state change <none> -> v1 ...
# removed offline-mirror per-host hosts.toml (rollback)` on every node. What it
# removed were the hosts.toml files k3s writes at its start from
# /etc/rancher/k3s/registries.yaml: the node's whole registry configuration
# under --disable-default-registry-endpoint. From then on containerd went to the
# public registries directly (`failed to fetch anonymous token ...
# https://ghcr.io/token`).
#
# EXECUTION of the rendered pivot.sh, its real reconcile loop, against a scratch
# certs.d holding what k3s v1.31.8+k3s1 writes: a stub curl is the API server
# (the status ConfigMap asks for the state of the scenario), a stub apk, and a
# stub sleep that ends each sweep: it copies certs.d, then plays the next step.
# Each part able to fail; on the chart before this change 1, 2, 3, 4 and 5 fail:
#   (1) the dormant first run (v1) leaves every file byte for byte and mode for
#       mode, and says so in its log;
#   (2) pivot then rollback: the pivot's files are gone and the node holds
#       exactly the files it held before, with their modes, no directory added;
#   (3) a file without the mark is never removed, also on a name the pivot
#       manages: k3s's _default and an unmanaged k3s name stay through the
#       pivot, a hand-written file on a pivoted name is kept aside and comes back;
#   (4) after the pivot no entry leaves a public registry reachable: every
#       pivoted name has a hosts.toml of the pivot whose endpoints are all on the
#       Sovereign's registry, and no file of certs.d has a `server` key naming
#       another host (containerd adds the upstream only when `server` is set or
#       no [host] is given: k3s-io/containerd v2.0.4-k3s2, parseHostsFile);
#   (5) a k3s restart after the cutover (k3s removes and rewrites the directory
#       of every registries.yaml name at its start, cleanContainerdHosts) is
#       followed by a sweep that pivots those names again;
#   (6) a node reboot (a new Pod, whose first sweep sees v2) pivots the names
#       k3s has just rewritten;
#   (7) a failed read of the status ConfigMap after the cutover (the API away,
#       a 5xx, the --max-time) changes nothing: the node keeps the pivot, acks
#       no v1, and the next read that succeeds finds it in place. Before this
#       rule the empty read became v1 and the node rolled back (fails on main).
#
# Usage: bash tests/registry-pivot-keeps-k3s-files.sh [CHART_DIR]
# shellcheck disable=SC2015,SC2016  # pass/fail chains; ${T_DIR} is expanded by the script under test
set -uo pipefail

CHART_DIR="${1:-$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")/.." && pwd)}"
CHART_DIR="$(cd "${CHART_DIR}" && pwd)"
TMP="$(mktemp -d)"
trap 'rm -rf "${TMP}"' EXIT
FAILURES=0
fail() { echo "  FAIL — $*"; FAILURES=$((FAILURES + 1)); }
pass() { echo "  ok   — $*"; }
K3S_HEADER="# File generated by k3s. DO NOT EDIT."
MARK="# managed by bp-self-sovereign-cutover registry-pivot ("

helm template ssc "${CHART_DIR}" --namespace catalyst --set sovereign.fqdn=sov.example.test \
  >"${TMP}/render.yaml" 2>"${TMP}/render.err" || { echo "helm template failed:"; cat "${TMP}/render.err"; exit 1; }

# pivot.sh: the block of ConfigMap registry-pivot-script, its 4 spaces of indent off.
awk '
  /^---/ { doc = 0; blk = 0 }
  /^  name: registry-pivot-script$/ { doc = 1 }
  blk && /^    / { print substr($0, 5); next }
  blk && /^ *$/ { print ""; next }
  blk { blk = 0 }
  doc && /^  pivot.sh: \|$/ { blk = 1 }
' "${TMP}/render.yaml" >"${TMP}/pivot.rendered.sh"
# The environment the DaemonSet gives the script (its literal values).
awk '
  /^---/ { ds = 0 }
  /^kind: DaemonSet$/ { ds = 1 }
  ds && /^ *- name: [A-Z_]+$/ { n = $3; next }
  ds && n != "" && /^ *value: / { v = $0; sub(/^ *value: /, "", v); gsub(/^"|"$/, "", v); printf "export %s=\047%s\047\n", n, v }
  { n = "" }
' "${TMP}/render.yaml" >"${TMP}/env.sh"
grep -q '^set -u$' "${TMP}/pivot.rendered.sh" && grep -q '^export HOST_PROJECT_MAP=' "${TMP}/env.sh" \
  || { echo "FAIL: the render has no pivot.sh or no HOST_PROJECT_MAP for the registry-pivot DaemonSet"; exit 1; }

# The node's paths become the scratch directory; each line must be found once, or the test is stale.
sed -e 's#^certs_d=/host/var/lib/rancher/k3s/agent/etc/containerd/certs.d$#certs_d="${T_DIR}/certs.d"#' \
  -e 's#^etc_hosts=/host/etc/hosts$#etc_hosts="${T_DIR}/hosts"#' \
  -e 's#^token=$(cat /var/run/secrets/kubernetes.io/serviceaccount/token)$#token=test#' \
  -e 's#touch /tmp/ready#touch "${T_DIR}/ready"#' "${TMP}/pivot.rendered.sh" >"${TMP}/pivot.sh"
for l in 'certs_d="${T_DIR}/certs.d"' 'etc_hosts="${T_DIR}/hosts"' 'token=test' 'touch "${T_DIR}/ready"'; do
  [ "$(grep -cF "${l}" "${TMP}/pivot.sh")" = "1" ] || { echo "FAIL: pivot.sh no longer has the line this test turns into ${l}"; exit 1; }
done

mkdir -p "${TMP}/bin"
cat >"${TMP}/bin/curl" <<'EOF'
#!/bin/sh
# The API server: the status ConfigMap asks for ${T_DIR}/state; writes succeed; the registry answers.
m=GET; w=0; prev=""; u=""
for a in "$@"; do
  [ "${prev}" = "-X" ] && m="${a}"
  [ "${a}" = "-w" ] && w=1
  prev="${a}"; u="${a}"
done
if [ "${w}" = "1" ]; then printf '200'; exit 0; fi
[ "${m}" = "GET" ] || exit 0
case "${u}" in
  */configmaps/"${STATUS_CONFIGMAP_NAME}")
    s=$(cat "${T_DIR}/state")
    [ "${s}" = fail ] && exit 22  # the read fails: curl -f prints nothing
    printf '{"data":{"registriesYamlActive":"%s","dragonflyUpstream":"local","node.%s.registriesYaml":"%s"}}\n' "${s}" "${NODE_NAME}" "${s}" ;;
  *) printf '{}\n' ;;
esac
EOF
printf '#!/bin/sh\nexit 0\n' >"${TMP}/bin/apk"
cat >"${TMP}/bin/sleep" <<'EOF'
#!/bin/sh
# A sweep has ended: copy certs.d to snap.<n>, then play the next step of the scenario.
n=$(($(cat "${T_DIR}/sweep") + 1))
echo "${n}" >"${T_DIR}/sweep"
cp -Rp "${T_DIR}/certs.d" "${T_DIR}/snap.${n}"
step=$(sed -n "$((n + 1))p" "${T_DIR}/scenario")
if [ -z "${step}" ]; then kill -TERM "${PPID}"; exit 0; fi
echo "${step%% *}" >"${T_DIR}/state"
case "${step}" in *k3s-restart*) sh "${T_DIR}/../k3s-start.sh" "${T_DIR}/certs.d" ;; esac
EOF
# What k3s v1.31.8+k3s1 does to certs.d at its start (pkg/agent/containerd/config.go,
# writeContainerdHosts and cleanContainerdHosts): it removes the directory of every name
# it writes and of every hosts.toml whose first line is its header, then writes its files.
cat >"${TMP}/k3s-start.sh" <<'EOF'
#!/bin/sh
c="$1"; k="$(dirname "$0")/k3s"
for n in $(cat "${k}.names"); do rm -rf "${c:?}/${n}"; done
for f in "${c}"/*/hosts.toml; do
  [ -f "${f}" ] || continue
  [ "$(head -n 1 "${f}")" = "# File generated by k3s. DO NOT EDIT." ] && rm -rf "$(dirname "${f}")"
done
for n in $(cat "${k}.names"); do mkdir -m 0700 -p "${c}/${n}" && cp -p "${k}/${n}/hosts.toml" "${c}/${n}/hosts.toml"; done
EOF
chmod +x "${TMP}/bin/curl" "${TMP}/bin/apk" "${TMP}/bin/sleep"

# shellcheck disable=SC1091
. "${TMP}/env.sh"
LOCAL="${LOCAL_REGISTRY_HOST}"
# shellcheck disable=SC2086  # the map is a list of words
set -- ${HOST_PROJECT_MAP}
[ "$#" -ge 4 ] || { echo "FAIL: the offline-mirror map has $# names, this test needs 4"; exit 1; }
MANAGED="${LOCAL}"
for pair in "$@"; do MANAGED="${MANAGED} ${pair%%:*}"; done
eval "HAND=\${$(($# - 1))%%:*}; NONE=\${$#%%:*}"
# k3s writes: the Sovereign's registry, every name of the map but the last two, an unmanaged name, and "*".
k3s_file() {  # $1 = project: what k3s renders for a mirror under --disable-default-registry-endpoint
  printf '%s\n\n[host]\n[host."https://%s/v2"]\n  capabilities = ["pull", "resolve"]\n' "${K3S_HEADER}" "${LOCAL}"
  [ -z "$1" ] || printf '  [host."https://%s/v2".rewrite]\n    "(.*)" = "%s/$1"\n' "${LOCAL}" "$1"
  printf '[host."https://harbor.openova.io/v2"]\n  capabilities = ["pull", "resolve"]\n'
}
: >"${TMP}/k3s.names"
for pair in "${LOCAL}:" "$@" "mirror.example.internal:x" "_default:"; do
  n="${pair%%:*}"
  { [ "${n}" = "${HAND}" ] || [ "${n}" = "${NONE}" ]; } && continue
  mkdir -p "${TMP}/k3s/${n}" && chmod 0700 "${TMP}/k3s/${n}"
  k3s_file "${pair#*:}" >"${TMP}/k3s/${n}/hosts.toml"
  chmod 0600 "${TMP}/k3s/${n}/hosts.toml"
  echo "${n}" >>"${TMP}/k3s.names"
done
mkdir -p "${TMP}/node/certs.d/${HAND}"
printf '# written on this node by hand\n[host."https://mirror.example.internal/v2"]\n' >"${TMP}/node/certs.d/${HAND}/hosts.toml"
cp -Rp "${TMP}/k3s/." "${TMP}/node/certs.d/"
cp -Rp "${TMP}/node" "${TMP}/node.orig"

run_pod() {  # $1 = node directory: one Pod of the DaemonSet, until its scenario ends
  echo 0 >"$1/sweep"
  read -r first _ <"$1/scenario"
  echo "${first}" >"$1/state"
  ( export T_DIR="$1" NODE_NAME=node-a HOST_IP=10.0.0.5 LOCAL_REGISTRY_PIN_ENABLED=false PATH="${TMP}/bin:${PATH}"
    timeout --foreground 60 sh "${TMP}/pivot.sh" >"$1/log" 2>&1 )
  [ "$?" != "124" ] || fail "pivot.sh did not reach the end of its scenario in 60s"
}
listing() { (cd "$1" && find . -printf '%y %m %p\n' | LC_ALL=C sort); }
same_tree() { diff -r "$1" "$2" >/dev/null 2>&1 && [ "$(listing "$1")" = "$(listing "$2")" ]; }
owned() { [ -f "$1" ] && [ "$(head -n 1 "$1" | cut -c1-${#MARK})" = "${MARK}" ]; }
all_owned() {  # $1 = certs.d: every managed name carries the pivot's hosts.toml
  for n in ${MANAGED}; do owned "$1/${n}/hosts.toml" || return 1; done
}

N="${TMP}/node"
printf 'v1\nv2\nv2 k3s-restart\nv1\n' >"${N}/scenario"
run_pod "${N}"

echo "[sov132] (1) the dormant first run changes no file and says so"
if same_tree "${TMP}/node.orig/certs.d" "${N}/snap.1"; then pass "certs.d after the first v1 sweep is the node's, file for file"
else fail "the first v1 sweep changed certs.d:"; diff -r "${TMP}/node.orig/certs.d" "${N}/snap.1" | sed 's/^/      /' | tail -20; fi
grep -q 'state change <none> -> v1' "${N}/log" && grep -q "registry files are left as they are" "${N}/log" \
  && pass "the log says the dormant run left the node's files" || fail "the log does not say the dormant run left the files"

echo "[sov132] (2) pivot then rollback leaves the node exactly with its own files"
if same_tree "${TMP}/node.orig/certs.d" "${N}/snap.4"; then pass "certs.d after the rollback is the node's, file for file and mode for mode"
else fail "after the rollback certs.d differs from the node's own:"; diff -r "${TMP}/node.orig/certs.d" "${N}/snap.4" | sed 's/^/      /' | tail -20; listing "${N}/snap.4" | tail -20; fi

echo "[sov132] (3) a file without the mark is never removed, also on a managed name"
for n in _default mirror.example.internal; do
  cmp -s "${TMP}/k3s/${n}/hosts.toml" "${N}/snap.2/${n}/hosts.toml" && pass "k3s's ${n}/hosts.toml is untouched by the pivot" \
    || fail "the pivot changed or removed k3s's ${n}/hosts.toml"
done
cmp -s "${TMP}/node.orig/certs.d/${HAND}/hosts.toml" "${N}/snap.2/${HAND}/hosts.toml.pre-pivot" \
  && pass "the hand-written ${HAND}/hosts.toml is kept aside while pivoted" || fail "the hand-written ${HAND}/hosts.toml was not kept"
cmp -s "${TMP}/node.orig/certs.d/${HAND}/hosts.toml" "${N}/snap.4/${HAND}/hosts.toml" \
  && pass "the hand-written ${HAND}/hosts.toml is back after the rollback" || fail "the hand-written ${HAND}/hosts.toml is gone"

echo "[sov132] (4) after the pivot no entry leaves a public registry reachable"
all_owned "${N}/snap.2" && pass "every managed name has the pivot's hosts.toml (${MANAGED})" \
  || fail "a managed name has no hosts.toml of the pivot after v2"
: >"${TMP}/bad"
for f in "${N}"/snap.2/*/hosts.toml; do
  grep -o '^server = "[^"]*"' "${f}" | sed 's/^server = //' | while read -r u; do
    case "${u}" in "\"https://${LOCAL}\""|"\"https://${LOCAL}/"*) ;; *) echo "${f#"${N}/snap.2/"}: server ${u}" >>"${TMP}/bad" ;; esac
  done
  owned "${f}" || continue
  grep -o '^\[host\."[^"]*"\]' "${f}" | while read -r h; do
    case "${h}" in "[host.\"https://${LOCAL}\"]"|"[host.\"https://${LOCAL}/"*) ;; *) echo "${f#"${N}/snap.2/"}: ${h}" >>"${TMP}/bad" ;; esac
  done
done
[ -s "${TMP}/bad" ] && fail "an entry reaches beyond ${LOCAL}:$(sed 's/^/ /' "${TMP}/bad" | head -5 | tr '\n' ';')" \
  || pass "every endpoint and server key is on ${LOCAL}"

echo "[sov132] (5) a k3s restart after the cutover is followed by a sweep that pivots again"
all_owned "${N}/snap.3" && grep -q "k3s rewrote the node's registry files" "${N}/log" \
  && pass "the sweep after the k3s restart pivoted every managed name again" \
  || fail "after the k3s restart a managed name stays on k3s's file"
first_k3s=$(head -n 1 "${TMP}/k3s.names")
cmp -s "${TMP}/k3s/${first_k3s}/hosts.toml" "${N}/snap.3/${first_k3s}/hosts.toml.pre-pivot" \
  && pass "k3s's rewritten ${first_k3s}/hosts.toml is kept aside" || fail "k3s's rewritten ${first_k3s}/hosts.toml was not kept"

echo "[sov132] (6) a node reboot: the new Pod pivots the names k3s has just written"
R="${TMP}/reboot"
mkdir -p "${R}"
cp -Rp "${N}/snap.2" "${R}/certs.d"
sh "${TMP}/k3s-start.sh" "${R}/certs.d"
all_owned "${R}/certs.d" && fail "the model of k3s's start left every pivot file in place" || pass "k3s's start replaced the pivoted names (the model bites)"
printf 'v2\n' >"${R}/scenario"
run_pod "${R}"
all_owned "${R}/snap.1" && pass "the first sweep of the new Pod pivoted every managed name" || fail "after the reboot a managed name stays on k3s's file"

echo "[sov132] (7) a failed read of the status ConfigMap keeps the pivot"
F="${TMP}/readfail"
mkdir -p "${F}"
cp -Rp "${TMP}/node.orig/certs.d" "${F}/certs.d"
printf 'v2\nfail\nv2\n' >"${F}/scenario"
run_pod "${F}"
all_owned "${F}/snap.1" && pass "the first sweep pivoted (the case bites)" || fail "the first v2 sweep did not pivot"
all_owned "${F}/snap.2" && pass "after the sweep whose read failed every managed name still has the pivot's file" \
  || fail "the sweep whose read failed removed the pivot's files"
grep -q -- '-> v1\|registriesYaml=v1' "${F}/log" && fail "the failed read led to v1: $(grep -- '-> v1\|registriesYaml=v1' "${F}/log" | head -n 2 | tr '\n' ' ')" \
  || pass "no state change to v1 and no v1 ack"
all_owned "${F}/snap.3" && [ "$(grep -c 'state change' "${F}/log")" = 1 ] \
  && pass "the next good read finds the pivot in place: one state change in the whole run" || fail "the sweep after the failed read changed the state again"

if [ "${FAILURES}" -gt 0 ]; then echo "registry-pivot-keeps-k3s-files: ${FAILURES} failure(s)"; exit 1; fi
echo "registry-pivot-keeps-k3s-files: all checks passed"
