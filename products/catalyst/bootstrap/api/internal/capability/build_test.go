// repoRoot is the repository root, from this package's folder.
const repoRoot = "../../../../../.."

func realSchema(t *testing.T, rel string) []byte {
	t.Helper()
	raw, err := fs.ReadFile(os.DirFS(repoRoot), rel)
	if err != nil {
		t.Fatal(err)
	}
	return raw
}

const objectStorage = `apiVersion: catalyst.openova.io/v1
kind: Capability
metadata:
  name: object-storage
spec:
  title: Object storage
  defaultImplementation: bp-object-bucket
  compositeKind: ObjectBucket
  contracts:
    - version: v1
      status: current
      keys:
        - {name: bucket, required: true, secret: false, description: Bucket name}
        - {name: secret-access-key, required: true, secret: true, description: Secret key}
      contextFields:
        - {name: retentionDays, type: integer, required: false, default: 0, description: Days to keep objects}
      probe: object-storage-v1
`

func blueprint(name, extra string) string {
	return "apiVersion: catalyst.openova.io/v1\nkind: Blueprint\nmetadata:\n  name: " + name + "\nspec:\n  version: 0.1.0\n" + extra
}

// goodTree: one contract file, two providers (listed out of order), one consumer, one Blueprint that has
// nothing to do with capabilities, and a folder without a blueprint.yaml.
func goodTree() map[string]string {
	return map[string]string{
		"platform/_capabilities/object-storage.yaml": objectStorage,
		"platform/object-bucket-managed/blueprint.yaml": blueprint("bp-object-bucket-managed",
			"  provides:\n    - {capability: object-storage, contract: v1, implementation: cloud-native}\n"),
		"platform/object-bucket/blueprint.yaml": blueprint("bp-object-bucket",
			"  provides:\n    - {capability: object-storage, contract: v1, implementation: in-cluster}\n"),
		"products/wiki/blueprint.yaml": blueprint("bp-wiki",
			"  requires:\n    - {capability: object-storage, contract: v1, alias: objects}\n"),
		"platform/cilium/blueprint.yaml": blueprint("bp-cilium", ""),
		"platform/_schemas/README.md":    "not a Blueprint folder\n",
	}
}

func writeTree(t *testing.T, files map[string]string) string {
	t.Helper()
	root := t.TempDir()
	for _, d := range []string{"platform", "products"} {
		if err := os.MkdirAll(filepath.Join(root, d), 0o750); err != nil {
			t.Fatal(err)
		}
	}
	for rel, body := range files {
		p := filepath.Join(root, rel)
		if err := os.MkdirAll(filepath.Dir(p), 0o750); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(body), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	return root
}

func TestBuildGoodTree(t *testing.T) {
	out, errs := Build(writeTree(t, goodTree()), realSchema(t, SchemaPath))
	if len(errs) > 0 {
		t.Fatalf("Build errors: %v", errs)
	}
	if !bytes.HasSuffix(out, []byte("}\n")) || !strings.Contains(string(out), "\n  \"capabilities\": [\n") {
		t.Fatalf("index is not indented JSON ending in a newline:\n%s", out)
	}
	var f struct {
		Comment      string `json:"comment"`
		Capabilities []struct {
			Name, Title, DefaultImplementation, CompositeKind string
			Contracts                                         []struct {
				Version, Status, Probe string
				Keys                   []struct {
					Name             string
					Required, Secret bool
				}
				ContextFields []struct {
					Name, Type string
					Default    interface{}
				}
			}
			Providers []Provider
		}
	}
	if err := json.Unmarshal(out, &f); err != nil {
		t.Fatal(err)
	}
	if !strings.HasPrefix(f.Comment, "Generated by sh products/catalyst/bootstrap/api/internal/capability/write.sh") {
		t.Fatalf("comment = %q", f.Comment)
	}
	if len(f.Capabilities) != 1 {
		t.Fatalf("capabilities = %+v, want object-storage only", f.Capabilities)
	}
	c := f.Capabilities[0]
	if c.Name != "object-storage" || c.Title != "Object storage" || c.DefaultImplementation != "bp-object-bucket" || c.CompositeKind != "ObjectBucket" {
		t.Fatalf("capability = %+v", c)
	}
	if len(c.Contracts) != 1 || c.Contracts[0].Version != "v1" || c.Contracts[0].Status != "current" || c.Contracts[0].Probe != "object-storage-v1" ||
		len(c.Contracts[0].Keys) != 2 || c.Contracts[0].Keys[1].Name != "secret-access-key" || !c.Contracts[0].Keys[1].Secret ||
		len(c.Contracts[0].ContextFields) != 1 || c.Contracts[0].ContextFields[0].Name != "retentionDays" || c.Contracts[0].ContextFields[0].Default != float64(0) {
		t.Fatalf("contracts = %+v", c.Contracts)
	}
	want := []Provider{{Blueprint: "bp-object-bucket", Contract: "v1", Implementation: "in-cluster"},
		{Blueprint: "bp-object-bucket-managed", Contract: "v1", Implementation: "cloud-native"}}
	if !reflect.DeepEqual(c.Providers, want) {
		t.Fatalf("providers = %+v, want %+v", c.Providers, want)
	}
	// The index the writer writes is the one the reader reads.
	idx, err := LoadIndex(out)
	if err != nil {
		t.Fatal(err)
	}
	if cur, ok := idx.Current("object-storage"); !ok || cur.Keys[0].Name != "bucket" || idx.DefaultImplementation("object-storage") != "bp-object-bucket" {
		t.Fatalf("LoadIndex of the written index: %+v %v", cur, ok)
	}
	// Deterministic: a second run writes the same bytes.
	again, _ := Build(writeTree(t, goodTree()), realSchema(t, SchemaPath))
	if !bytes.Equal(out, again) {
		t.Fatal("two runs on one tree differ")
	}
}

func TestBuildNoContractFolder(t *testing.T) {
	files := goodTree()
	for rel := range files {
		if strings.Contains(rel, "_capabilities") || strings.Contains(rel, "object-bucket") || strings.HasPrefix(rel, "products/") {
			delete(files, rel)
		}
	}
	out, errs := Build(writeTree(t, files), realSchema(t, SchemaPath))
	if len(errs) > 0 {
		t.Fatalf("errors: %v", errs)
	}
	want := "{\n  \"comment\": \"Generated by sh products/catalyst/bootstrap/api/internal/capability/write.sh from platform/_capabilities/*.yaml and every blueprint.yaml. Do not edit.\",\n  \"capabilities\": []\n}\n"
	if string(out) != want {
		t.Fatalf("index =\n%s\nwant\n%s", out, want)
	}
}

// TestBuildRefuses — every failure mode, each on its own copy of the good tree, and the message names the file.
func TestBuildRefuses(t *testing.T) {
	cases := []struct {
		name, file, body, want string
		drop                   string
	}{
		{name: "contract fails the schema", file: "platform/_capabilities/object-storage.yaml",
			body: strings.Replace(objectStorage, "      probe: object-storage-v1\n", "", 1), want: "platform/_capabilities/object-storage.yaml: fails platform/_schemas/capability.schema.json"},
		{name: "contract name is not the file name", file: "platform/_capabilities/object-storage.yaml",
			body: strings.Replace(objectStorage, "name: object-storage\n", "name: objects\n", 1), want: `metadata.name is "objects", the file name says "object-storage"`},
		{name: "contract version listed twice", file: "platform/_capabilities/object-storage.yaml",
			body: objectStorage + "    - {version: v1, status: deprecated, keys: [{name: bucket, required: true, secret: false, description: d}], contextFields: [], probe: p}\n",
			want: "contract version v1 is listed twice"},
		{name: "context field default of the wrong type", file: "platform/_capabilities/object-storage.yaml",
			body: strings.Replace(objectStorage, "default: 0", "default: none", 1), want: `platform/_capabilities/object-storage.yaml: contract v1: the default of context field "retentionDays" does not fit it`},
		{name: "contract is not YAML", file: "platform/_capabilities/object-storage.yaml", body: "spec: [\n", want: "platform/_capabilities/object-storage.yaml: yaml: line 1: did not find expected node content"},
		{name: "blueprint.yaml is not YAML", file: "platform/cilium/blueprint.yaml", body: "spec: [\n", want: "platform/cilium/blueprint.yaml: not YAML: yaml: line 1"},
		{name: "provides names a capability with no contract file", file: "platform/cilium/blueprint.yaml",
			body: blueprint("bp-cilium", "  provides:\n    - {capability: firewall, contract: v1, implementation: in-cluster}\n"),
			want: `platform/cilium/blueprint.yaml: spec.provides names capability "firewall", which has no file platform/_capabilities/firewall.yaml`},
		{name: "requires names a contract version the file does not declare", file: "products/wiki/blueprint.yaml",
			body: blueprint("bp-wiki", "  requires:\n    - {capability: object-storage, contract: v2, alias: objects}\n"),
			want: `products/wiki/blueprint.yaml: spec.requires names object-storage contract "v2", which platform/_capabilities/object-storage.yaml does not declare`},
		{name: "defaultImplementation does not provide the capability", drop: "platform/object-bucket/blueprint.yaml",
			want: "platform/_capabilities/object-storage.yaml: defaultImplementation bp-object-bucket does not provide object-storage"},
		{name: "capability provided twice", file: "platform/object-bucket/blueprint.yaml",
			body: blueprint("bp-object-bucket", "  provides:\n    - {capability: object-storage, contract: v1, implementation: in-cluster}\n    - {capability: object-storage, contract: v1, implementation: cloud-native}\n"),
			want: `platform/object-bucket/blueprint.yaml: spec.provides lists capability "object-storage" twice`},
		{name: "alias required twice", file: "products/wiki/blueprint.yaml",
			body: blueprint("bp-wiki", "  requires:\n    - {capability: object-storage, contract: v1, alias: objects}\n    - {capability: object-storage, contract: v1, alias: objects}\n"),
			want: `products/wiki/blueprint.yaml: spec.requires lists alias "objects" twice`},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			files := goodTree()
			if tc.file != "" {
				files[tc.file] = tc.body
			}
			delete(files, tc.drop)
			out, errs := Build(writeTree(t, files), realSchema(t, SchemaPath))
			if out != nil || !strings.Contains(strings.Join(errs, "\n"), tc.want) {
				t.Fatalf("errors %q (index %d bytes), want one containing %q", errs, len(out), tc.want)
			}
		})
	}
	t.Run("missing products folder", func(t *testing.T) {
		root := writeTree(t, goodTree())
		if err := os.RemoveAll(filepath.Join(root, "products")); err != nil {
			t.Fatal(err)
		}
		if _, errs := Build(root, realSchema(t, SchemaPath)); !strings.Contains(strings.Join(errs, "\n"), "products/: input folder cannot be read") {
			t.Fatalf("errors %q", errs)
		}
	})
}

// TestBlueprintSchemaCapabilityFields — platform/_schemas/blueprint.schema.json: provides and requires as the
// definition declares them, and a Blueprint with provides must be shareable.
func TestBlueprintSchemaCapabilityFields(t *testing.T) {
	c := jsonschema.NewCompiler()
	c.Draft = jsonschema.Draft2020
	if err := c.AddResource("file:///blueprint.schema.json", bytes.NewReader(realSchema(t, "platform/_schemas/blueprint.schema.json"))); err != nil {
		t.Fatal(err)
	}
	schema, err := c.Compile("file:///blueprint.schema.json")
	if err != nil {
		t.Fatal(err)
	}
	head := "apiVersion: catalyst.openova.io/v1\nkind: Blueprint\nmetadata: {name: bp-store}\nspec:\n  version: 0.1.0\n  class: data-service\n  lifecycle: experimental\n  visibility: unlisted\n  card: {title: X}\n"
	shareable := "  shareable: true\n  contextSchema: {kind: bucket, valuesKey: buckets}\n"
	provides := "  provides: [{capability: object-storage, contract: v1, implementation: in-cluster}]\n"
	cases := []struct {
		name, spec string
		ok         bool
	}{
		{"provides on a shareable Blueprint", shareable + provides, true},
		{"requires with an optional entry", "  requires: [{capability: object-storage, contract: v1, alias: objects, optional: true}]\n", true},
		{"provides without shareable", provides, false},
		{"provides with shareable false", "  shareable: false\n" + provides, false},
		{"provides with an unknown implementation", shareable + "  provides: [{capability: object-storage, contract: v1, implementation: managed}]\n", false},
		{"provides without contract", shareable + "  provides: [{capability: object-storage, implementation: in-cluster}]\n", false},
		{"requires with a bad contract version", "  requires: [{capability: object-storage, contract: '1', alias: objects}]\n", false},
		{"requires with an unknown key", "  requires: [{capability: object-storage, contract: v1, alias: objects, implementation: bp-x}]\n", false},
	}
	for _, tc := range cases {
		js, err := yaml.YAMLToJSON([]byte(head + tc.spec))
		if err != nil {
			t.Fatal(err)
		}
		var doc interface{}
		if err := json.Unmarshal(js, &doc); err != nil {
			t.Fatal(err)
		}
		if err := schema.Validate(doc); (err == nil) != tc.ok {
			t.Errorf("%s: valid=%v, want %v (%v)", tc.name, err == nil, tc.ok, err)
		}
	}
}
