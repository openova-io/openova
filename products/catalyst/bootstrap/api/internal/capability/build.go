// Paths of the index writer, relative to the repository root.
const (
	ContractsDir = "platform/_capabilities"
	SchemaPath   = "platform/_schemas/capability.schema.json"
	IndexPath    = "products/catalyst/bootstrap/api/internal/catalog/capabilities.json"
	WriteCommand = "sh products/catalyst/bootstrap/api/internal/capability/write.sh"
)

// blueprintSources are the Blueprint files the catalogue generator reads (scripts/generate-catalog.py).
var blueprintSources = []string{"platform", "products"}

// contractFile is the YAML of platform/_capabilities/<name>.yaml.
type contractFile struct {
	Metadata struct {
		Name string `json:"name"`
	} `json:"metadata"`
	Spec struct {
		Title                 string     `json:"title"`
		DefaultImplementation string     `json:"defaultImplementation"`
		CompositeKind         string     `json:"compositeKind"`
		Contracts             []Contract `json:"contracts"`
	} `json:"spec"`
}

// provision is one entry of a blueprint.yaml's spec.provides.
type provision struct {
	Capability     string `json:"capability"`
	Contract       string `json:"contract"`
	Implementation string `json:"implementation"`
}

// blueprintFile is the part of a blueprint.yaml the index reads.
type blueprintFile struct {
	Metadata struct {
		Name string `json:"name"`
	} `json:"metadata"`
	Spec struct {
		Provides []provision   `json:"provides"`
		Requires []Requirement `json:"requires"`
	} `json:"spec"`
}

// Build reads the tree at root and returns the capability index (the bytes of capabilities.json), or the
// input errors, one line each, naming the file. schema is platform/_schemas/capability.schema.json.
//
// Errors: a contract file that is not YAML or fails the schema; a contract whose metadata.name is not its
// file name, or that lists one version twice, or whose field default or enum does not fit the field's type; a
// blueprint.yaml that is not YAML; a Blueprint that provides one capability twice or requires one alias
// twice; a provides or requires entry that names a capability or contract version with no contract file; a
// contract whose defaultImplementation does not provide it; a missing platform/ or products/ folder. A
// missing platform/_capabilities/ folder is no error: it holds no contract, so the index is an empty list.
func Build(root string, schema []byte) ([]byte, []string) {
	tree := os.DirFS(root)
	var errs []string
	compiled, err := compileSchema(schema)
	if err != nil {
		return nil, []string{SchemaPath + ": " + err.Error()}
	}
	contracts, cErrs := readContracts(tree, compiled)
	errs = append(errs, cErrs...)

	providers := map[string][]Provider{}
	for _, top := range blueprintSources {
		dirs, err := fs.ReadDir(tree, top)
		if err != nil {
			errs = append(errs, top+"/: input folder cannot be read: "+err.Error())
			continue
		}
		for _, d := range dirs {
			if !d.IsDir() {
				continue
			}
			rel := top + "/" + d.Name() + "/blueprint.yaml"
			raw, err := fs.ReadFile(tree, rel)
			if errors.Is(err, fs.ErrNotExist) {
				continue
			}
			if err != nil {
				errs = append(errs, rel+": "+err.Error())
				continue
			}
			var bp blueprintFile
			if err := decodeYAML(raw, &bp, nil); err != nil {
				errs = append(errs, rel+": not YAML: "+err.Error())
				continue
			}
			errs = append(errs, checkBlueprint(rel, bp, contracts)...)
			for _, p := range bp.Spec.Provides {
				providers[p.Capability] = append(providers[p.Capability],
					Provider{Blueprint: bp.Metadata.Name, Contract: p.Contract, Implementation: p.Implementation})
			}
		}
	}

	out := file{Comment: "Generated by " + WriteCommand + " from " + ContractsDir + "/*.yaml and every blueprint.yaml. Do not edit.",
		Capabilities: []entry{}}
	names := make([]string, 0, len(contracts))
	for n := range contracts {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		cf := contracts[n]
		ps := providers[n]
		sort.Slice(ps, func(i, j int) bool { return ps[i].Blueprint < ps[j].Blueprint })
		def := false
		for _, p := range ps {
			def = def || p.Blueprint == cf.Spec.DefaultImplementation
		}
		if !def {
			errs = append(errs, fmt.Sprintf("%s/%s.yaml: defaultImplementation %s does not provide %s (no blueprint.yaml of %s lists it in spec.provides)",
				ContractsDir, n, cf.Spec.DefaultImplementation, n, strings.Join(blueprintSources, "/ or ")+"/"))
		}
		if ps == nil {
			ps = []Provider{}
		}
		out.Capabilities = append(out.Capabilities, entry{Name: n, Title: cf.Spec.Title, DefaultImplementation: cf.Spec.DefaultImplementation,
			CompositeKind: cf.Spec.CompositeKind, Contracts: cf.Spec.Contracts, Providers: ps})
	}
	if len(errs) > 0 {
		return nil, errs
	}
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetIndent("", "  ")
	enc.SetEscapeHTML(false)
	if err := enc.Encode(out); err != nil {
		return nil, []string{IndexPath + ": " + err.Error()}
	}
	return buf.Bytes(), nil
}

func compileSchema(schema []byte) (*jsonschema.Schema, error) {
	c := jsonschema.NewCompiler()
	c.Draft = jsonschema.Draft2020
	if err := c.AddResource("file:///capability.schema.json", bytes.NewReader(schema)); err != nil {
		return nil, err
	}
	return c.Compile("file:///capability.schema.json")
}

// decodeYAML converts YAML to JSON, checks it against schema when one is given, and decodes it into v.
func decodeYAML(raw []byte, v interface{}, schema *jsonschema.Schema) error {
	js, err := yaml.YAMLToJSON(raw)
	if err != nil {
		return err
	}
	if schema != nil {
		var doc interface{}
		if err := json.Unmarshal(js, &doc); err != nil {
			return err
		}
		if err := schema.Validate(doc); err != nil {
			return schemaFailure(err)
		}
	}
	return json.Unmarshal(js, v)
}

// schemaFailure lists every failing leaf of a validation error, sorted, on one line.
func schemaFailure(err error) error {
	var ve *jsonschema.ValidationError
	if !errors.As(err, &ve) {
		return err
	}
	var leaves []string
	var walk func(*jsonschema.ValidationError)
	walk = func(e *jsonschema.ValidationError) {
		if len(e.Causes) == 0 {
			leaves = append(leaves, "at '"+e.InstanceLocation+"': "+e.Message)
		}
		for _, c := range e.Causes {
			walk(c)
		}
	}
	walk(ve)
	sort.Strings(leaves)
	return fmt.Errorf("fails %s: %s", SchemaPath, strings.Join(leaves, "; "))
}

// readContracts reads every platform/_capabilities/*.yaml, keyed by capability name.
func readContracts(tree fs.FS, schema *jsonschema.Schema) (map[string]contractFile, []string) {
	out := map[string]contractFile{}
	var errs []string
	files, err := fs.ReadDir(tree, ContractsDir)
	if errors.Is(err, fs.ErrNotExist) {
		return out, nil
	}
	if err != nil {
		return out, []string{ContractsDir + "/: cannot be read: " + err.Error()}
	}
	for _, f := range files {
		if f.IsDir() || !strings.HasSuffix(f.Name(), ".yaml") {
			continue
		}
		rel := ContractsDir + "/" + f.Name()
		raw, err := fs.ReadFile(tree, rel)
		if err != nil {
			errs = append(errs, rel+": "+err.Error())
			continue
		}
		var cf contractFile
		if err := decodeYAML(raw, &cf, schema); err != nil {
			errs = append(errs, rel+": "+err.Error())
			continue
		}
		if want := strings.TrimSuffix(f.Name(), ".yaml"); cf.Metadata.Name != want {
			errs = append(errs, fmt.Sprintf("%s: metadata.name is %q, the file name says %q", rel, cf.Metadata.Name, want))
			continue
		}
		seen := map[string]bool{}
		for _, c := range cf.Spec.Contracts {
			if seen[c.Version] {
				errs = append(errs, fmt.Sprintf("%s: contract version %s is listed twice", rel, c.Version))
			}
			seen[c.Version] = true
			for _, fld := range c.ContextFields {
				if fld.Default != nil {
					if _, err := fld.check(fld.Default); err != nil {
						errs = append(errs, fmt.Sprintf("%s: contract %s: the default of context field %q does not fit it: %v", rel, c.Version, fld.Name, err))
					}
				}
				for _, e := range fld.Enum {
					if _, err := (ContextField{Name: fld.Name, Type: fld.Type}).check(e); err != nil {
						errs = append(errs, fmt.Sprintf("%s: contract %s: an enum value of context field %q is not of its type: %v", rel, c.Version, fld.Name, err))
					}
				}
			}
		}
		out[cf.Metadata.Name] = cf
	}
	return out, errs
}

// checkBlueprint: each provides and requires entry names a contract file and one of its versions; no
// capability is provided twice and no alias required twice.
func checkBlueprint(rel string, bp blueprintFile, contracts map[string]contractFile) []string {
	var errs []string
	known := func(field, capability, version string) {
		cf, ok := contracts[capability]
		if !ok {
			errs = append(errs, fmt.Sprintf("%s: spec.%s names capability %q, which has no file %s/%s.yaml", rel, field, capability, ContractsDir, capability))
			return
		}
		for _, c := range cf.Spec.Contracts {
			if c.Version == version {
				return
			}
		}
		errs = append(errs, fmt.Sprintf("%s: spec.%s names %s contract %q, which %s/%s.yaml does not declare", rel, field, capability, version, ContractsDir, capability))
	}
	provided := map[string]bool{}
	for _, p := range bp.Spec.Provides {
		if provided[p.Capability] {
			errs = append(errs, fmt.Sprintf("%s: spec.provides lists capability %q twice", rel, p.Capability))
		}
		provided[p.Capability] = true
		known("provides", p.Capability, p.Contract)
	}
	aliases := map[string]bool{}
	for _, r := range bp.Spec.Requires {
		if aliases[r.Alias] {
			errs = append(errs, fmt.Sprintf("%s: spec.requires lists alias %q twice", rel, r.Alias))
		}
		aliases[r.Alias] = true
		known("requires", r.Capability, r.Contract)
	}
	return errs
}
