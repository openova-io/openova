// Package orgtenantrepos holds the cutover-aware addresses of the Organization
// tenants tree: the image registry host of its overlays (vcluster_registry.go,
// #5439) and its shared HelmRepository file
// (clusters/<fqdn>/org-tenants/helmrepositories.yaml): the six
// blocks every per-Organization overlay takes its charts from, and the one
// decision that picks their catalog, the public one (oci://ghcr.io/openova-io)
// or the Sovereign's own registry (oci://registry.<fqdn>/openova-io).
// internal/handler writes the file (writeParentTenantsIndex, on every
// Organization write and teardown) and re-renders it before the cutover's
// egress hold (repointOrgTenantSources); Flux applies it through the
// Kustomization org-tenants.
//
// Measured 21 Nov 2026 on a two-region install: cutover step 06
// (helmrepository-patches) moved the HelmRepositories that existed between
// 04:03:25 and 04:06:10; an Organization written at 04:08:19 made the engine
// write this file with the public catalog, because the engine decided
// "pivoted" from the issuer pair that step 07 stamps and the Pod carrying it
// was only created at 04:09:37. Nothing wrote the file again, and step 08 failed
// three Pods on OFFENDER bp-agenity, bp-openclaw, bp-stalwart-tenant and
// bp-wordpress-tenant=oci://ghcr.io/openova-io. RegistryPivoted therefore also
// reads the cutover's own status, which the engine writes the moment the
// Sovereign's registry serves every chart, and NamesPublicCatalog lets the
// re-render find a file written before that moment.
package orgtenantrepos

import "strings"

// GHCRBase is the public catalog every block declares before the pivot.
const GHCRBase = "oci://ghcr.io/openova-io"

// FileName is the file's name inside clusters/<fqdn>/org-tenants/.
const FileName = "helmrepositories.yaml"

// StatusKeyRegistries is the key of the cutover status ConfigMap
// (catalyst/self-sovereign-cutover-status) that carries the registry pivot.
// The engine sets it to "v2" when step harbor-prewarm succeeds (handler
// cutover.go runCutoverWith): from then on the Sovereign's registry serves
// every chart and image, and the registry-pivot DaemonSet (step 04) points
// every node at it. Nothing in the engine writes it back; the chart creates
// the ConfigMap once (lookup guard, #3667), so a helm upgrade does not either.
// "v1" (the initial value) and "rollback" are not pivoted.
const StatusKeyRegistries = "registriesYamlActive"

