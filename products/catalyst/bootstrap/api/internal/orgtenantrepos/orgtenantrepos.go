// RegistryPivoted reports whether this Sovereign's registry has been pivoted,
// from two facts; either one is enough.
//
//   - The cutover status (status, the data of the status ConfigMap; nil when it
//     could not be read): StatusKeyRegistries is "v2". It is the earliest true
//     signal: it is written when harbor-prewarm succeeds, before step 04
//     (registry-pivot) and step 06 (helmrepository-patches), and it is read
//     without a new Pod. The step results (step.<name>.result) are not used:
//     the engine clears them when it re-runs a step (#5437), which would turn
//     the answer back to "not pivoted" in the middle of a cutover.
//   - The issuer pair that step 07 (catalyst-api-env-patch) stamps on the
//     catalyst-api Deployment, CATALYST_PIN_ISSUER or
//     CATALYST_HANDOVER_JWT_ISSUER (#5527). It was chosen because nothing else
//     sets either variable, so its presence is uniquely the cutover's, and it
//     survives restarts and helm upgrades. It stays a fact here (a Sovereign
//     whose status cannot be read). Its other readers are unchanged: the
//     issuer of the console's sessions (handler auth.go pinIssuer, agenttoken),
//     of the hand-over tokens (handoverjwt signer.go) and the image-registry
//     host of the org-tenant overlay (VClusterImageRegistry, vcluster_registry.go).
//
// Neither fact holds on the mothership, which has no cutover.
func RegistryPivoted(env func(string) string, status map[string]string) bool {
	if strings.TrimSpace(env("CATALYST_PIN_ISSUER")) != "" ||
		strings.TrimSpace(env("CATALYST_HANDOVER_JWT_ISSUER")) != "" {
		return true
	}
	return strings.TrimSpace(status[StatusKeyRegistries]) == "v2"
}

// Base returns the OCI base the six blocks declare.
//
//   - CATALYST_LOCAL_REGISTRY_URL, when set, is the base (Inviolable Principle
//     #4), normalised to oci://<host>/<path> without a trailing slash.
//   - Pivoted (RegistryPivoted): oci://registry.<fqdn>/openova-io, the value
//     step 06 patches the live objects to, so the file and the objects agree.
//     The fqdn is SOVEREIGN_FQDN, else CATALYST_OTECH_FQDN.
//   - Otherwise, and when pivoted without an fqdn: GHCRBase.
func Base(env func(string) string, status map[string]string) string {
	if v := strings.TrimSpace(env("CATALYST_LOCAL_REGISTRY_URL")); v != "" {
		if !strings.HasPrefix(v, "oci://") {
			v = "oci://" + v
		}
		return strings.TrimSuffix(v, "/")
	}
	if !RegistryPivoted(env, status) {
		return GHCRBase
	}
	fqdn := strings.TrimSpace(env("SOVEREIGN_FQDN"))
	if fqdn == "" {
		fqdn = strings.TrimSpace(env("CATALYST_OTECH_FQDN"))
	}
	if fqdn == "" {
		return GHCRBase
	}
	return "oci://registry." + fqdn + "/openova-io"
}

// Render returns the file with every block on base. On GHCRBase it is
// Template, byte for byte, so a regeneration before the pivot is no drift.
func Render(base string) string {
	if base == GHCRBase {
		return Template
	}
	return strings.ReplaceAll(Template, "url: "+GHCRBase, "url: "+base)
}

// NamesPublicCatalog reports whether doc still declares a url on the public
// catalog: the file a re-render after the pivot has to rewrite.
func NamesPublicCatalog(doc []byte) bool {
	for _, line := range strings.Split(string(doc), "\n") {
		if strings.TrimSpace(line) == "url: "+GHCRBase {
			return true
		}
	}
	return false
}
